//! # Операторы (Statements) в Rust — учебный пример (пункт 1.10)
//!
//! Этот файл завершает базовый синтаксический блок. В пунктах 1.1–1.9 мы
//! разобрали «кирпичи» языка: лексемы, макросы, элементы, атрибуты,
//! операторы (символы), типы, выражения и шаблоны. Теперь посмотрим, как
//! из них собирается **исполняемая единица** — блок и его операторы.
//!
//! **Оператор (statement)** — это компонент блока. В отличие от выражения,
//! оператор **не производит значения** для окружающего контекста (хотя
//! внутри может вычислять выражения).
//!
//! Rust имеет два вида операторов:
//!   1. **Объявления (declaration statements)** — вводят имена:
//!      * `let`-операторы;
//!      * объявления элементов (item declarations).
//!   2. **Операторы-выражения (expression statements)** — вычисляют
//!      выражение и **отбрасывают** результат.
//!
//! Дополнительные формы:
//!   * пустой оператор `;`;
//!   * вызов макроса с `;`;
//!   * `let ... else` (с опровержимым шаблоном).
//!
//! **Ключевое правило:** блок `{ ... }` — это последовательность операторов,
//! за которой может идти **хвостовое выражение** (без `;`). Именно
//! хвостовое выражение (или его отсутствие) определяет значение блока.

// ============================================================================
// ПОДГОТОВКА: данные для демонстраций
// ============================================================================

#[derive(Debug)]
struct Point {
    x: i32,
    y: i32,
}

fn add(a: i32, b: i32) -> i32 {
    a + b
}

// ============================================================================
// 1. ПУСТОЙ ОПЕРАТОР `;`
// ============================================================================
// Одиночная точка с запятой — **пустой оператор**. Он ничего не делает,
// но иногда полезен для явного завершения блока или как заглушка.

fn empty_statement_demo() {
    // Пустой оператор в блоке:
    ;
    println!("после пустого оператора");

    // Блок, состоящий только из пустых операторов, возвращает `()`:
    let unit: () = {
        ;
        ;
    };
    println!("unit = {unit:?}");
}

// ============================================================================
// 2. `LET`-ОПЕРАТОРЫ
// ============================================================================
// Синтаксис (упрощённо):
//     let [атрибуты] ПАТТЕРН [: Тип] [= выражение] [else { ... }] ;
//
// * `let` вводит **новые переменные** в текущий блок.
// * Тип может быть указан явно или выведен компилятором.
// * Если `else` отсутствует, шаблон должен быть **неопровержимым**
//   (irrefutable): он всегда совпадает.
// * Если `else` присутствует, шаблон может быть **опровержимым**
//   (refutable), а блок `else` должен **дивергировать** (иметь тип `!`:
//   `panic!`, `return`, `break`, `continue`).
// * Переменные видны с точки объявления до конца блока (с учётом затенения).

fn let_statements_demo() {
    // ----- Базовый `let` с выводом типа -----
    let inferred = 42; // компилятор выведет `i32`
    println!("inferred = {inferred}");

    // ----- `let` с явной аннотацией типа -----
    let explicit: f64 = 3.14;
    println!("explicit = {explicit}");

    // ----- `let` с шаблоном (деструктуризация) -----
    let (a, b) = (1, 2);
    println!("a = {a}, b = {b}");

    let Point { x, y } = Point { x: 10, y: 20 };
    println!("x = {x}, y = {y}");

    // ----- `let` без инициализатора (отложенная инициализация) -----
    // Переменная должна быть инициализирована до первого чтения.
    let deferred: i32;
    deferred = 100;
    println!("deferred = {deferred}");

    // ----- Затенение (shadowing) -----
    // Новый `let` с тем же именем создаёт **новую** переменную,
    // скрывая предыдущую. Тип может отличаться.
    let shadowed = 5;
    let shadowed = shadowed * 2;      // 10
    let shadowed = shadowed.to_string(); // "10" (другой тип!)
    println!("shadowed = {shadowed}");

    // ----- `let` с атрибутом -----
    // Атрибуты могут применяться к `let`-операторам.
    #[allow(unused_variables)]
    let with_attribute = 1;
}

// ============================================================================
// 3. `LET ... ELSE` — ОПРОВЕРЖИМЫЙ ШАБЛОН
// ============================================================================
// Стабильно с Rust 1.65. Позволяет «развернуть» значение, если шаблон
// совпал, и выполнить **дивергентный** блок `else` в противном случае.
//
// Это удобная замена `match`/`if let`, когда нужен ранний выход.

fn let_else_demo() {
    // ----- С `Option` -----
    let maybe_number = Some(7);
    let Some(n) = maybe_number else {
        // Блок `else` должен дивергировать.
        println!("значение отсутствует — выходим");
        return;
    };
    println!("n = {n}");

    // ----- С `Result` -----
    let parsed: Result<i32, _> = "42".parse::<i32>();
    let Ok(value) = parsed else {
        println!("не удалось распарсить");
        return;
    };
    println!("value = {value}");

    // ----- С пользовательским enum -----
    let point = Some(Point { x: 1, y: 2 });
    let Some(Point { x, y }) = point else {
        println!("точки нет");
        return;
    };
    println!("точка: ({x}, {y})");
}

// ============================================================================
// 4. ОБЪЯВЛЕНИЯ ЭЛЕМЕНТОВ ВНУТРИ БЛОКА (ITEM DECLARATIONS)
// ============================================================================
// Внутри блока можно объявлять элементы: `fn`, `struct`, `enum`, `use` и др.
// Их синтаксис совпадает с объявлением на уровне модуля, но **область
// видимости ограничена блоком**.
//
// ВАЖНО: вложенная `fn` — это **самостоятельный элемент**, а не замыкание.
// Она **не захватывает** переменные и параметры внешней функции.

fn item_declaration_demo() {
    // Вложенная функция:
    fn inner_add(a: i32, b: i32) -> i32 {
        a + b
    }

    // Вложенная структура:
    #[derive(Debug)]
    struct LocalPoint {
        x: i32,
        y: i32,
    }

    // Вложенный `use`:
    use std::collections::HashMap;

    println!("inner_add(2, 3) = {}", inner_add(2, 3));

    let p = LocalPoint { x: 5, y: 6 };
    println!("local point = {p:?}");

    let mut map = HashMap::new();
    map.insert("one", 1);
    println!("map = {map:?}");

    // Демонстрация отсутствия захвата:
    let outer_var = 10;
    fn cannot_capture() {
        // println!("{outer_var}"); // ОШИБКА: `outer_var` не видна здесь
    }
    cannot_capture();
    let _ = outer_var;
}

// ============================================================================
// 5. ОПЕРАТОРЫ-ВЫРАЖЕНИЯ (EXPRESSION STATEMENTS)
// ============================================================================
// Оператор-выражение вычисляет выражение и **отбрасывает** результат.
// Обычно завершается `;`.
//
// Исключение: выражения, состоящие из блока или управляющей конструкции
// (`if`, `match`, `loop`, `while`, `for`), могут **опускать** `;`.
// Это не создаёт неоднозначности, потому что такие выражения и так
// имеют тип `()` в позиции оператора (кроме `loop` с `break value`).

fn expression_statements_demo() {
    // ----- Обычное выражение с `;` -----
    add(2, 3); // результат 5 отброшен
    println!("add(2, 3) вызвана как оператор");

    // ----- Вызов метода с `;` -----
    let mut v = vec![1, 2, 3];
    v.push(4); // результат `()` и так, но `;` завершает оператор
    println!("v = {v:?}");

    // ----- Оператор-выражение с блоком (без `;`) -----
    {
        let inner = 10;
        println!("внутри блока: inner = {inner}");
    } // значение блока `()` отброшено

    // ----- Управляющие выражения как операторы (без `;`) -----
    if true {
        println!("if как оператор");
    }

    match 1 {
        1 => println!("match как оператор"),
        _ => {}
    }

    for i in 0..3 {
        println!("for как оператор: i = {i}");
    }

    // ----- `loop` с `break value` требует `;` -----
    // Потому что `loop` может производить значение.
    let mut counter = 0;
    let result = loop {
        counter += 1;
        if counter == 3 {
            break counter * 10; // значение `loop`
        }
    };
    println!("loop returned {result}");

    // Если `loop` используется как оператор и не возвращает значение,
    // `;` не обязателен, но обычно ставится для ясности.
    loop {
        break;
    }
}

// ============================================================================
// 6. МАКРОСЫ КАК ОПЕРАТОРЫ
// ============================================================================
// Вызов макроса, завершённый `;`, — это отдельная форма оператора
// (`MacroInvocationSemi`). Например, `println!(...);`, `vec![...];` и т.д.

fn macro_statement_demo() {
    // Макрос-оператор:
    println!("макрос как оператор");

    // `vec!` как оператор — результат отброшен:
    vec![1, 2, 3];

    // Макрос с блоком и без `;`:
    // (Некоторые макросы допускают отсутствие `;`, если возвращают `()`.)
    assert_eq!(2 + 2, 4);
}

// ============================================================================
// 7. ОБЛАСТЬ ВИДИМОСТИ И БЛОКИ
// ============================================================================
// Каждый блок `{ ... }` создаёт новую область видимости.
// Переменные, введённые внутри блока, **не видны** снаружи.
// Вложенные блоки могут **затенять** внешние переменные.

fn scope_and_blocks_demo() {
    let outer = 1;
    println!("outer (внешний) = {outer}");

    {
        let inner = 2;
        println!("inner = {inner}");

        // Затенение внешней переменной:
        let outer = 100;
        println!("outer (затенённый) = {outer}");
    }
    // println!("{inner}"); // ОШИБКА: `inner` не видна здесь
    println!("outer (снова внешний) = {outer}"); // 1

    // Вложенные блоки произвольной глубины:
    {
        {
            let deep = 42;
            println!("deep = {deep}");
        }
    }
}

// ============================================================================
// 8. ОПЕРАТОРЫ VS ВЫРАЖЕНИЯ: ГРАНИЦА
// ============================================================================
// Один и тот же синтаксис может быть оператором или выражением
// в зависимости от контекста и наличия `;`.
//
//   * `{ ... }` в позиции выражения — выражение (производит значение).
//   * `{ ... }` в позиции оператора — оператор (значение отброшено).
//   * `if cond { 1 } else { 2 }` — выражение типа `i32`.
//   * `if cond { 1 } else { 2 };` — оператор, результат отброшен.

fn statement_vs_expression_demo() {
    // Выражение:
    let value = if true { 1 } else { 2 };
    println!("value = {value}");

    // Оператор:
    if true { 1 } else { 2 }; // результат отброшен

    // Блок как выражение:
    let from_block = {
        let a = 2;
        let b = 3;
        a + b
    };
    println!("from_block = {from_block}");

    // Тот же блок как оператор:
    {
        let a = 2;
        let b = 3;
        a + b; // `;` превращает хвостовое выражение в оператор
    }
}

// ============================================================================
// ТОЧКА ВХОДА
// ============================================================================

fn main() {
    println!("=== 1. Пустой оператор `;` ===");
    empty_statement_demo();

    println!("\n=== 2. `let`-операторы ===");
    let_statements_demo();

    println!("\n=== 3. `let ... else` ===");
    let_else_demo();

    println!("\n=== 4. Объявления элементов в блоке ===");
    item_declaration_demo();

    println!("\n=== 5. Операторы-выражения ===");
    expression_statements_demo();

    println!("\n=== 6. Макросы как операторы ===");
    macro_statement_demo();

    println!("\n=== 7. Область видимости и блоки ===");
    scope_and_blocks_demo();

    println!("\n=== 8. Операторы vs выражения ===");
    statement_vs_expression_demo();
}