//! # Ящики и исходные файлы в Rust — учебный пример (пункт 1.3)
//!
//! **Крейт (crate)** — это единица компиляции в Rust. Компилятор `rustc`
//! всегда компилирует ровно один крейт за раз. Существует два основных вида:
//!
//! * **Бинарный крейт** — имеет точку входа `fn main()` и компилируется
//!   в исполняемый файл. Корневой файл обычно называется `main.rs`.
//! * **Библиотечный крейт** — не имеет `main`, компилируется в библиотеку
//!   (`.rlib`). Корневой файл обычно называется `lib.rs`.
//!
//! В этом файле мы находимся в **корне бинарного крейта** (`main.rs`).
//! Отсюда компилятор начинает обход всех модулей.

// ============================================================================
// 1. АТРИБУТЫ УРОВНЯ КРЕЙТА (inner attributes)
// ============================================================================
// Внутренние атрибуты `#![...]` применяются ко **всему крейту**.
// Они должны идти в самом начале файла, до любых элементов.

// Задаём имя крейта (по умолчанию — имя файла без расширения).
// При сборке через Cargo этот атрибут может конфликтовать с настройками
// пакета, поэтому при использовании Cargo его лучше закомментировать.
#![crate_name = "rusthierarchy"]

// Задаём тип крейта: `bin` — исполняемая программа, `lib` — библиотека,
// `rlib` — библиотека Rust и т.д.
#![crate_type = "bin"]

// Отключаем предупреждение о неиспользуемых переменных, чтобы
// сосредоточиться на демонстрации, а не на мелочах.
#![allow(unused_variables)]

// Условно применяем атрибут: если включена фича `extra`, добавляем
// `#![allow(dead_code)]` ко всему крейту. Если фича выключена —
// атрибут не применяется.
#![cfg_attr(feature = "extra", allow(dead_code))]

// ============================================================================
// 2. МОДУЛИ (inline-объявление)
// ============================================================================
// Модуль — это пространство имён для элементов (функций, структур и т.д.).
// В корневом файле `main.rs` модуль можно объявить **inline** — прямо в
// фигурных скобках. Альтернатива — `mod math;`, тогда компилятор будет
// искать `math.rs` или `math/mod.rs` в той же директории.
//
// По умолчанию всё внутри модуля **приватно**. Чтобы элементы были
// доступны снаружи, используется ключевое слово `pub`.

/// Модуль с простыми математическими операциями.
/// Демонстрирует inline-объявление модуля и видимость (`pub`).
mod math {
    /// Публичная функция: доступна как `math::add(...)`.
    pub fn add(a: i32, b: i32) -> i32 {
        a + b
    }

    /// Приватная функция: доступна только внутри модуля `math`.
    fn private_helper() -> i32 {
        42
    }

    /// Публичная функция, использующая приватную.
    pub fn answer() -> i32 {
        private_helper()
    }
}

/// Вложенный модуль: модуль внутри модуля.
/// Путь к функции: `nested::inner::greet()`.
mod nested {
    pub mod inner {
        pub fn greet() {
            println!("Привет из вложенного модуля!");
        }
    }
}

// ============================================================================
// 3. УСЛОВНАЯ КОМПИЛЯЦИЯ (#[cfg] и cfg!)
// ============================================================================
// Атрибут `#[cfg(...)]` включает или выключает элемент на этапе компиляции.
// Условия могут быть простыми (`foo`) или составными
// (`any(...)`, `all(...)`, `not(...)`).

/// Модуль, который компилируется **только** если включена фича `extra`.
/// При обычной сборке (без `--cfg 'feature="extra"'`) этого модуля
/// в программе не существует.
#[cfg(feature = "extra")]
mod extra {
    pub fn hello() {
        println!("Модуль extra включён (фича `extra` активна).");
    }
}

/// Функция, которая компилируется только под Linux.
/// На других ОС её просто не будет в бинарнике.
#[cfg(target_os = "linux")]
fn linux_only() {
    println!("Эта функция существует только на Linux.");
}

/// Функция, которая компилируется только под Windows.
#[cfg(target_os = "windows")]
fn windows_only() {
    println!("Эта функция существует только на Windows.");
}

// `cfg!` — это макрос, который раскрывается в `true` или `false`
// на этапе компиляции. В отличие от `#[cfg]`, он не удаляет код,
// а позволяет использовать условие внутри выражений.
fn conditional_runtime_branch() {
    if cfg!(feature = "extra") {
        println!("cfg!(feature = \"extra\") = true");
    } else {
        println!("cfg!(feature = \"extra\") = false");
    }

    if cfg!(target_os = "linux") {
        println!("Мы на Linux (по мнению cfg!).");
    } else if cfg!(target_os = "windows") {
        println!("Мы на Windows (по мнению cfg!).");
    } else {
        println!("Мы на другой ОС.");
    }
}

// ============================================================================
// 4. ИСПОЛЬЗОВАНИЕ ПУТЕЙ И `use`
// ============================================================================
// Полный путь к элементу: `crate::math::add`.
// `crate` — это корень текущего крейта (файл `main.rs`).
// Ключевое слово `use` создаёт локальный псевдоним для пути.

use crate::math::add;          // теперь можно писать `add(...)`
use crate::nested::inner;      // теперь можно писать `inner::greet()`

// `use` можно комбинировать в группы:
#[warn(unused_imports)]
use crate::math::{answer, add as plus}; // `plus` — псевдоним для `add`

// ============================================================================
// 5. ВНЕШНИЕ КРЕЙТЫ (extern crate)
// ============================================================================
// Если бы мы использовали внешнюю библиотеку (например, `rand`),
// в Rust 2015 требовалось бы объявление `extern crate rand;`.
// В Rust 2018+ и новее `extern crate` обычно не нужен: достаточно
// указать зависимость в `Cargo.toml`, и имя крейта становится
// доступно в путях (`rand::thread_rng()`).
//
// Пример (не компилируется без зависимости):
//     extern crate rand;
//     use rand::Rng;
//
// Здесь мы оставляем только комментарий, чтобы файл оставался
// самодостаточным.

// ============================================================================
// ТОЧКА ВХОДА
// ============================================================================

fn main() {
    println!("=== 2. Модули ===");
    // Обращение к публичной функции модуля по полному пути:
    let sum = math::add(2, 3);
    println!("math::add(2, 3) = {}", sum);

    // Через псевдоним, созданный `use`:
    let difference = plus(10, 4) - answer(); // answer() = 42
    println!("10 + 4 - 42 = {}", difference);

    // Вложенный модуль:
    nested::inner::greet();

    // Использование псевдонимов из `use`:
    println!("plus(7, 8) = {}", plus(7, 8));
    inner::greet(); // то же, что nested::inner::greet()

    println!("\n=== 3. Условная компиляция ===");

    // Код, который существует только при включённой фиче `extra`.
    // Если фича выключена, этот блок не компилируется.
    #[cfg(feature = "extra")]
    {
        extra::hello();
    }

    // Код, который существует только на Linux.
    #[cfg(target_os = "linux")]
    linux_only();

    // Код, который существует только на Windows.
    #[cfg(target_os = "windows")]
    windows_only();

    // Ветвление на этапе выполнения, основанное на compile-time флагах:
    conditional_runtime_branch();

    println!("\n=== 4. Пути и use ===");
    println!("Полный путь: crate::math::add(1, 1) = {}", crate::math::add(1, 1));
    println!("Короткий путь: add(1, 1) = {}", add(1, 1));
}

// ============================================================================
// СПРАВКА: как скомпилировать и запустить
// ============================================================================
// 1) Без фичи `extra` (модуль `extra` отсутствует):
//        rustc main.rs && ./main
//
// 2) С фичей `extra` (модуль `extra` включается):
//        rustc --cfg 'feature="extra"' main.rs && ./main
//
// 3) Кросс-платформенная проверка:
//        rustc --print cfg    # покажет все доступные cfg-флаги
//
// 4) Если вы используете Cargo, закомментируйте `#![crate_name]` и
//    `#![crate_type]` в начале файла, чтобы избежать конфликтов.
//
// 5) Чтобы вынести модуль `math` в отдельный файл:
//    - создайте `math.rs` рядом с `main.rs`;
//    - переместите туда содержимое `mod math { ... }` (без обёртки `mod`);
//    - в `main.rs` замените inline-модуль на `mod math;`.
//    Компилятор автоматически найдёт `math.rs` и включит его в крейт.