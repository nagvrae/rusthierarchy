// 6. ПУНКТУАЦИЯ И ОПЕРАТОРЫ (краткий обзор)
// ============================================================
// Основные символы-токены Rust (полный список — The Rust Reference, гл. «Tokens»):
//   +  -  *  /  %  !  &  |  ^  <<  >>  &&  ||  ==  !=  <  <=  >  >=
//   =  += -= *= /= %= &= |= ^= <<= >>=
//   ->  .  ..  ..=  ...  ::  ;  :  ,  =>  @  ?  #  $  _  (  )  [  ]  {  }

/// Демонстрация базовой пунктуации.
fn punctuation_demo() {
    let a = 10;
    let b = 3;

    // Арифметика
    println!("{} + {} = {}", a, b, a + b);
    println!("{} - {} = {}", a, b, a - b);
    println!("{} * {} = {}", a, b, a * b);
    println!("{} / {} = {}", a, b, a / b);   // целочисленное деление
    println!("{} % {} = {}", a, b, a % b);

    // Логика
    let cond = a > b && b > 0 || false;
    println!("(a > b && b > 0) || false = {cond}");

    // Диапазоны: `..` — исключающий, `..=` — включающий
    let exclusive: std::ops::Range<i32>          = 1..5;    // 1,2,3,4
    let inclusive: std::ops::RangeInclusive<i32> = 1..=5;   // 1,2,3,4,5
    println!("exclusive={exclusive:?}, inclusive={inclusive:?}");

    // `_` — wildcard, например, при игнорировании значения в шаблоне:
    let (x, _) = (1, 2);
    println!("x={x}");
}

