//! # Атрибуты и производные (derive) — учебный пример (пункт 1.5)
//!
//! **Атрибут** — это метаданные, которые применяются к элементу кода
//! (крейту, модулю, структуре, функции и т.д.) и влияют на его компиляцию
//! или документацию.
//!
//! Формы записи:
//!   * `#[атрибут]`       — **внешний** атрибут: применяется к элементу,
//!                          который идёт **сразу после** него.
//!   * `#![атрибут]`      — **внутренний** атрибут: применяется ко **всему**
//!                          элементу, внутри которого находится (обычно к
//!                          модулю или крейту).
//!
//! Аргументы атрибута могут быть:
//!   * без аргументов:     `#[test]`
//!   * со значением:       `#[doc = "..."]`
//!   * в скобках:          `#[derive(Debug, Clone)]`
//!   * с ключ-значение:    `#[cfg(feature = "extra")]`

// ============================================================================
// 1. ВНУТРЕННИЕ АТРИБУТЫ УРОВНЯ КРЕЙТА
// ============================================================================
// `#![...]` в начале файла применяется ко всему крейту.
// В п. 1.3 мы уже видели `#![crate_name]` и `#![crate_type]`;
// здесь — атрибуты, управляющие линтами (предупреждениями компилятора).

// Отключаем предупреждение о неиспользуемых переменных во всём крейте.
#![allow(unused_variables)]

// Устанавливаем уровень линта `dead_code` в `warn` (по умолчанию он `warn`,
// но здесь показан явно). Уровни: allow, warn, deny, forbid.
#![warn(dead_code)]

// `cfg_attr` — условное применение атрибута. Если фича `strict`
// включена, применяется `#![deny(missing_docs)]`, иначе — ничего.
// (См. также раздел 6.)
#![cfg_attr(feature = "strict", deny(missing_docs))]

// ============================================================================
// 2. ОСНОВНЫЕ ВСТРОЕННЫЕ АТРИБУТЫ: ДИАГНОСТИКА (ЛИНТЫ)
// ============================================================================
// Атрибуты `allow`, `warn`, `deny`, `forbid` управляют уровнем
// предупреждений для конкретного линта. Область действия — элемент,
// к которому применён атрибут, и все вложенные элементы.

/// Функция с неиспользуемой переменной: предупреждение подавлено.
#[allow(unused_variables)]
fn suppressed_warning() {
    let x = 42; // обычно было бы предупреждение — подавлено `allow`
}

/// Функция, где неиспользуемая переменная вызовет предупреждение.
#[warn(unused_variables)]
fn warned_function() {
    let y = 10; // сработает предупреждение (в реальном коде)
}

/// `deny` превращает предупреждение в ошибку компиляции.
/// Если раскомментировать строку ниже, компиляция не пройдёт.
// #[deny(unused_variables)]
// fn denied_function() { let z = 1; }

// ============================================================================
// 3. DERIVE-АТРИБУТ: АВТОМАТИЧЕСКАЯ РЕАЛИЗАЦИЯ ТРЕЙТОВ
// ============================================================================
// `#[derive(...)]` — один из самых распространённых атрибутов.
// Он вызывает **derive-макросы**, которые автоматически генерируют
// реализации указанных трейтов для структуры, перечисления или union.
//
// Встроенные derive-трейты (из прелюдии):
//   Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd.

/// `Debug` позволяет печатать через `{:?}`,
/// `Clone` — клонировать, `PartialEq` — сравнивать через `==`.
#[derive(Debug, Clone, PartialEq)]
struct Point {
    x: i32,
    y: i32,
}

/// `Default` создаёт значение по умолчанию (все поля — `Default::default()`).
/// `PartialOrd` позволяет сравнивать через `<`, `>`, `<=`, `>=`.
#[derive(Debug, Default, PartialOrd, PartialEq)]
struct Config {
    timeout: u32,
    retries: u8,
}

/// Derive можно применять к перечислениям.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
enum Direction {
    North,
    South,
    East,
    West,
}

// ============================================================================
// 4. АТРИБУТЫ, ВЛИЯЮЩИЕ НА КОДОГЕНЕРАЦИЮ И ПРЕДСТАВЛЕНИЕ
// ============================================================================

/// `#[repr(C)]` задаёт C-совместимое расположение полей в памяти.
/// Полезно для FFI (взаимодействия с C-кодом).
#[repr(C)]
struct CStruct {
    a: i32,
    b: f64,
}

/// `#[repr(u8)]` для enum задаёт размер дискриминанта (1 байт).
#[repr(u8)]
enum SmallEnum {
    A = 1,
    B = 2,
    C = 3,
}

/// `#[inline]` — подсказка компилятору встраивать функцию в место вызова.
/// `#[inline(always)]` — более настойчивая подсказка, `#[inline(never)]` —
/// запрет на встраивание.
#[inline]
fn fast_add(a: i32, b: i32) -> i32 {
    a + b
}

#[inline(always)]
fn always_inline() -> &'static str {
    "всегда inline"
}

#[inline(never)]
fn never_inline() -> &'static str {
    "никогда не inline"
}

// ============================================================================
// 5. АТРИБУТЫ ЖИЗНЕННОГО ЦИКЛА И ПРЕДУПРЕЖДЕНИЙ
// ============================================================================

/// `#[deprecated]` помечает элемент как устаревший.
/// При использовании будет выдано предупреждение с указанным сообщением.
#[deprecated(since = "1.0.0", note = "используйте `new_api` вместо `old_api`")]
fn old_api() {
    println!("старый API");
}

fn new_api() {
    println!("новый API");
}

/// `#[must_use]` требует, чтобы возвращаемое значение функции
/// было использовано (иначе — предупреждение).
#[must_use = "результат вычисления нельзя игнорировать"]
fn compute() -> i32 {
    42
}

// ============================================================================
// 6. УСЛОВНАЯ КОМПИЛЯЦИЯ: `cfg` И `cfg_attr`
// ============================================================================
// В п. 1.3 мы уже касались `#[cfg(...)]`. Здесь — более полный обзор.

/// Функция существует только при включённой фиче `extra`.
#[cfg(feature = "extra")]
fn extra_function() {
    println!("фича `extra` включена");
}

/// `cfg_attr` применяет атрибут **условно**:
/// если фича `debug_impls` включена — добавляется `#[derive(Debug)]`,
/// иначе структура остаётся без `Debug`.
#[cfg_attr(feature = "debug_impls", derive(Debug))]
struct ConditionalDebug {
    value: i32,
}

// `cfg!` — макрос, возвращающий `true`/`false` на этапе компиляции.
// В отличие от `#[cfg]`, он не удаляет код, а позволяет ветвить логику.
fn cfg_macro_demo() {
    if cfg!(feature = "extra") {
        println!("cfg!(feature = \"extra\") = true");
    } else {
        println!("cfg!(feature = \"extra\") = false");
    }
}

// ============================================================================
// 7. АТРИБУТЫ ДОКУМЕНТАЦИИ
// ============================================================================
// `#[doc = "..."]` — эквивалент doc-комментария `///`.
// `#[doc(...)]` с ключ-значение управляет настройками `rustdoc`.

/// Это обычный doc-комментарий, эквивалентный
/// `#[doc = "Это обычный doc-комментарий..."]`.
#[doc = "Дополнительная документация через атрибут `doc`."]
fn documented_function() {}

// `#[doc(hidden)]` скрывает элемент из сгенерированной документации.
#[doc(hidden)]
fn hidden_from_docs() {}

// ============================================================================
// 8. АТРИБУТЫ ТЕСТИРОВАНИЯ
// ============================================================================

/// `#[test]` помечает функцию как тест. Тесты запускаются через `cargo test`.
#[test]
fn test_addition() {
    assert_eq!(2 + 2, 4);
}

/// Тест с ожидаемым паником.
#[test]
#[should_panic(expected = "деление на ноль")]
fn test_division_by_zero() {
    let _ = 1 / 0; // в реальном коде нужно обрабатывать, здесь — для демонстрации
}

// ============================================================================
// 9. ПОЛЬЗОВАТЕЛЬСКИЕ DERIVE-МАКРОСЫ (теоретическая часть)
// ============================================================================
// Встроенных derive-макросов достаточно для большинства задач, но можно
// создавать свои. Для этого нужен **отдельный крейт** с `proc-macro = true`.
//
// Пример определения (в отдельном крейте `my_derive`):
//
//     use proc_macro::TokenStream;
//     use quote::quote;
//     use syn::{parse_macro_input, DeriveInput};
//
//     #[proc_macro_derive(Hello)]
//     pub fn derive_hello(input: TokenStream) -> TokenStream {
//         let ast = parse_macro_input!(input as DeriveInput);
//         let name = &ast.ident;
//         let expanded = quote! {
//             impl #name {
//                 fn hello() -> &'static str { "Hello!" }
//             }
//         };
//         expanded.into()
//     }
//
// Тогда в основном коде:
//     #[derive(Hello)]
//     struct MyStruct;
//     MyStruct::hello(); // "Hello!"
//
// Мы не можем определить такой макрос в этом же файле, поэтому
// ограничиваемся демонстрацией встроенных derive.

// ============================================================================
// ТОЧКА ВХОДА
// ============================================================================

fn main() {
    println!("=== 3. Derive: автоматическая реализация ===");
    let p1 = Point { x: 1, y: 2 };
    let p2 = p1.clone(); // Clone
    println!("p1 = {:?}, p2 = {:?}", p1, p2); // Debug
    println!("p1 == p2: {}", p1 == p2); // PartialEq

    let default_config = Config::default();
    println!("Config::default() = {:?}", default_config);

    let dir = Direction::North;
    println!("dir = {:?}", dir);

    println!("\n=== 4. Кодогенерация и repr ===");
    println!("size_of::<CStruct>() = {}", std::mem::size_of::<CStruct>());
    println!("size_of::<SmallEnum>() = {}", std::mem::size_of::<SmallEnum>());
    println!("fast_add(2, 3) = {}", fast_add(2, 3));
    println!("{}", always_inline());
    println!("{}", never_inline());

    println!("\n=== 5. Устаревшие и must_use ===");
    // Вызов устаревшей функции вызовет предупреждение компилятора.
    #[allow(deprecated)]
    old_api();
    new_api();
    let _ = compute(); // значение использовано — предупреждения нет
    // compute(); // если раскомментировать — предупреждение `must_use`

    println!("\n=== 6. Условная компиляция ===");
    #[cfg(feature = "extra")]
    extra_function();
    cfg_macro_demo();

    let cond = ConditionalDebug { value: 10 };
    // Если фича `debug_impls` включена, работает `{:?}`; иначе — ошибка.
    #[cfg(feature = "debug_impls")]
    println!("ConditionalDebug = {:?}", cond);

    println!("\n=== 7. Документация ===");
    documented_function();
    hidden_from_docs();

    println!("\n=== 8. Тесты ===");
    println!("Тесты запускаются через `cargo test`");
    // Ручной вызов тестовых функций не требуется.
}

// ============================================================================
// МОДУЛЬ ТЕСТОВ (необязательно)
// ============================================================================
// В реальном проекте тесты обычно помещают в модуль `#[cfg(test)]`.
// Здесь мы уже определили тесты выше с помощью `#[test]`, но
// для демонстрации паттерна `#[cfg(test)]` приведём его:

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn point_equality() {
        let a = Point { x: 1, y: 2 };
        let b = Point { x: 1, y: 2 };
        assert_eq!(a, b); // работает благодаря `#[derive(PartialEq)]`
    }

    #[test]
    fn config_default() {
        let c = Config::default();
        assert_eq!(c.timeout, 0);
        assert_eq!(c.retries, 0);
    }
}

