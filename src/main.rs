// 2. ИДЕНТИФИКАТОРЫ
// ============================================================
// Правила:
//   * Начинаются с буквы (включая Unicode) или `_`, но НЕ с цифры.
//   * Далее — буквы, цифры, `_`.
//   * Регистрозависимы: `foo` и `Foo` — разные.
// Соглашения (не правила компилятора):
//   * snake_case         — переменные, функции, модули;
//   * UpperCamelCase     — типы, трейты, enum-варианты;
//   * SCREAMING_SNAKE_CASE — `const` и `static`.
//
// Ключевые слова как идентификаторы: через префикс `r#`
//   let r#match = 10;   // `match` — ключевое слово, но `r#match` — валидное имя
//   let r#type  = 20;

// ============================================================
// 3. КЛЮЧЕВЫЕ СЛОВА (зарезервированы, использовать как имена нельзя)
// ============================================================
//   as, break, const, continue, crate, dyn, else, enum, extern,
//   false, fn, for, if, impl, in, let, loop, match, mod, move,
//   mut, pub, ref, return, self, Self, static, struct, super,
//   trait, true, type, unsafe, use, where, while, async, await
//
// Слабо зарезервированные (используются только в спец. контекстах):
//   abstract, become, box, do, final, macro, override, priv,
