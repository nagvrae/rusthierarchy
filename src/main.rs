//! # Макросы в Rust — учебный пример (пункт 1.2)
//!
//! Макросы — это механизм метапрограммирования: код, который **пишет код**.
//! В отличие от функций, макросы раскрываются на этапе компиляции и
//! работают с токенами (а не со значениями).
//!
//! В Rust есть два вида макросов:
//!   1. **Декларативные** (`macro_rules!`) — сопоставление с образцом.
//!   2. **Процедурные** — функции, принимающие и возвращающие `TokenStream`.
//!
//! !!! Важно: процедурные макросы **нельзя определить в этом же файле**.
//! Они требуют отдельного крейта с `proc-macro = true` в `Cargo.toml`.
//! Ниже мы покажем их *использование* и дадим примеры определений в комментариях.

// ============================================================================
// ЧАСТЬ 1. ДЕКЛАРАТИВНЫЕ МАКРОСЫ (`macro_rules!`)
// ============================================================================
// Синтаксис: `macro_rules! имя { (образец) => { раскрытие }; ... }`
// Каждое правило — это «образец => раскрытие», разделённые `;`.
// Макрос вызывается как `имя!(...)`, `имя![...]` или `имя!{...}` —
// ограничители взаимозаменяемы (по соглашению используют `()`).

/// 1.1. Простейший макрос без аргументов.
/// `()` означает «нет аргументов».
macro_rules! say_hello {
    () => {
        println!("Привет из макроса!");
    };
}

/// 1.2. Макрос с одним аргументом.
/// `$name:expr` — фрагментный спецификатор `expr`:
/// он соответствует любому **выражению**.
macro_rules! greet {
    ($name:expr) => {
        println!("Привет, {}!", $name);
    };
}

/// 1.3. Демонстрация фрагментных спецификаторов (fragment specifiers).
/// Спецификатор сообщает макросу, какой синтаксис ожидается на входе.
macro_rules! show_fragments {
    // `expr` — любое выражение.
    (expr: $e:expr) => {
        println!("expr = {:?}", $e);
    };
    // `ident` — идентификатор (имя переменной, функции, типа).
    (ident: $i:ident) => {
        println!("ident = {}", stringify!($i));
    };
    // `ty` — тип.
    (ty: $t:ty) => {
        // `Default::default()` даёт значение по умолчанию для типа.
        let _: $t = Default::default();
        println!("ty = {}", stringify!($t));
    };
    // `literal` — литерал.
    (literal: $l:literal) => {
        println!("literal = {}", $l);
    };
    // `tt` — «дерево токенов», самый гибкий спецификатор:
    // соответствует почти любой последовательности токенов.
    (tt: $($t:tt)*) => {
        println!("tt = {}", stringify!($($t)*));
    };
}

/// 1.4. Макрос с повторениями (вариадический).
/// `$( ... ),*` означает «повторить ноль или более раз, разделяя запятыми».
/// `$( ... ),+` — «один или более раз».
macro_rules! make_vec {
    ($($e:expr),*) => {
        {
            let mut v = Vec::new();
            // `$( v.push($e); )*` — повторяем `push` для каждого `$e`.
            $( v.push($e); )*
            v
        }
    };
}

/// 1.5. Несколько правил с разными образцами.
/// Макрос выбирает первое совпавшее правило.
macro_rules! describe {
    // Правило для одного аргумента.
    ($x:expr) => {
        println!("Один аргумент: {:?}", $x);
    };
    // Правило для двух аргументов.
    ($x:expr, $y:expr) => {
        println!("Два аргумента: {:?} и {:?}", $x, $y);
    };
    // «Ловушка» для всего остального: ноль аргументов или больше двух.
    () => {
        println!("Нет аргументов");
    };
    ($($x:expr),+ $(,)?) => {
        println!("Много аргументов: {}", stringify!($($x),+));
    };
}

/// 1.6. Гигиена макросов.
/// Переменная `x`, введённая **внутри** макроса, не конфликтует
/// с переменной `x` в месте вызова — это называется «гигиеной».
/// Однако идентификаторы, переданные **снаружи**, сохраняют свой контекст.
macro_rules! hygiene_demo {
    () => {
        let x = "внутри макроса";
        println!("Изнутри: {}", x);
    };
}

// ============================================================================
// ЧАСТЬ 2. ПРОЦЕДУРНЫЕ МАКРОСЫ
// ============================================================================
// В отличие от `macro_rules!`, процедурные макросы — это **функции**,
// которые принимают `TokenStream` и возвращают `TokenStream`.
// Они определяются в отдельном крейте (см. `Cargo.toml` ниже) и бывают
// трёх видов: derive, attribute и function-like.

// --- 2.1. Derive-макросы -----------------------------------------------------
// Использование: `#[derive(Debug)]`, `#[derive(Clone)]` и т.д.
// Встроенный derive `Debug` автоматически реализует трейт `Debug`,
// позволяя печатать структуру через `{:?}`.
#[derive(Debug)]
struct Point {
    x: i32,
    y: i32,
}

// --- 2.2. Атрибутные макросы -------------------------------------------------
// Использование: `#[test]`, `#[cfg(...)]`, а также пользовательские атрибуты.
// Например, встроенный `#[test]` превращает функцию в тест.
// Пользовательский атрибут мог бы выглядеть так:
//     #[route(GET, "/api/users")]
//     fn list_users() { ... }
// Определение (в отдельном крейте):
//     #[proc_macro_attribute]
//     pub fn route(attr: TokenStream, item: TokenStream) -> TokenStream { ... }

// --- 2.3. Function-like макросы ----------------------------------------------
// Использование: `sql!(...)`, `html!(...)` и т.п.
// Выглядят как вызовы функций, но работают с токенами.
// Пример вызова (определение — в отдельном крейте):
//     let query = sql!("SELECT * FROM users WHERE id = $1");
//
// Пример определения (в отдельном крейте):
//     use proc_macro::TokenStream;
//     use quote::quote;
//     #[proc_macro]
//     pub fn sql(input: TokenStream) -> TokenStream {
//         let sql_str = input.to_string();
//         quote! { /* код, использующий #sql_str */ }.into()
//     }

// ============================================================================
// ТОЧКА ВХОДА
// ============================================================================

fn main() {
    // ---------- Вызовы декларативных макросов ----------
    println!("--- 1.1. say_hello ---");
    say_hello!();

    println!("\n--- 1.2. greet ---");
    greet!("Алиса");
    greet!(String::from("Боб"));   // принимает любое выражение
    greet!(2 + 2);                 // даже арифметическое выражение

    println!("\n--- 1.3. show_fragments ---");
    show_fragments!(expr: 1 + 2 * 3);
    show_fragments!(ident: my_variable);
    show_fragments!(ty: Vec<String>);
    show_fragments!(literal: "строка");
    show_fragments!(tt: a b c 123);

    println!("\n--- 1.4. make_vec ---");
    let v = make_vec![1, 2, 3, 4];
    println!("v = {:?}", v);

    println!("\n--- 1.5. describe ---");
    describe!();
    describe!(42);
    describe!("a", "b");
    describe!(1, 2, 3);

    println!("\n--- 1.6. hygiene_demo ---");
    let x = "снаружи";
    hygiene_demo!();
    println!("Снаружи: {}", x);

    // ---------- Процедурные макросы в действии ----------
    println!("\n--- 2.1. Derive (Debug) ---");
    let p = Point { x: 10, y: 20 };
    // `{:?}` работает благодаря автоматической реализации `Debug`
    // от derive-макроса.
    println!("p = {:?}", p);
    println!("p.x = {}, p.y = {}", p.x, p.y);

    // ---------- Встроенные макросы для сравнения ----------
    println!("\n--- Встроенные макросы ---");
    // `vec!` — декларативный макрос из стандартной библиотеки.
    let builtin_vec = vec![1, 2, 3];
    println!("builtin_vec = {:?}", builtin_vec);

    // `println!`, `format!`, `assert_eq!` и др. — тоже макросы.
    let s = format!("{} + {} = {}", 2, 2, 2 + 2);
    println!("{}", s);
    assert_eq!(2 + 2, 4);
    println!("assert_eq! прошёл успешно");
}

// ============================================================================
// СПРАВКА: как настроить отдельный крейт для процедурных макросов
// ============================================================================
// В `Cargo.toml` крейта-библиотеки:
//
//     [lib]
//     proc-macro = true
//
//     [dependencies]
//     syn = "2"
//     quote = "1"
//     proc-macro2 = "1"
//
// `syn` парсит входной `TokenStream` в AST, `quote` генерирует код,
// `proc-macro2` даёт стабильный API поверх `proc_macro`.
//
// После этого в `src/lib.rs` можно объявлять:
//     #[proc_macro_derive(MyTrait)]
//     #[proc_macro_attribute]
//     #[proc_macro]
//
// И использовать в обычном `main.rs`, подключив этот крейт как зависимость.