/// Демонстрация литералов всех видов.
fn literals_demo() {
    // ----- Целочисленные литералы -----
    let dec  = 1_000_000;      // десятичный; `_` — просто разделитель для читаемости
    let hex  = 0xFF;           // шестнадцатеричный  (255)
    let oct  = 0o77;           // восьмеричный       (63)
    let bin  = 0b1010_1010;    // двоичный           (170)
    let bc   = b'A';           // байтовый литерал: `u8`, значение 65

    // Литералы с явным суффиксом-типом (пишется без пробела — это ОДИН токен):
    let small: u8    = 255u8;
    let big          = 1_000_000_000i64;
    let unsigned     = 42_usize;

    // ----- Вещественные литералы -----
    let f1 = 3.14;             // по умолчанию f64
    let f2 = 2.0f32;           // явный f32
    let f3 = 1.5e10;           // экспоненциальная запись = 1.5 × 10¹⁰
    let f4 = 1_000.000_1;      // `_` работает и в дробной части

    // ----- Символьные литералы (char — 4 байта, Unicode scalar) -----
    let c1 = 'A';
    let c2 = 'я';              // русская буква — валидный char
    let c3 = '\n';             // escape-последовательность
    let c4 = '\u{1F600}';      // Unicode-код (эмодзи 😀)
    let c5 = '\'';             // экранированная одинарная кавычка

    // ----- Строковые литералы (&str, всегда UTF-8) -----
    let s1 = "Hello, world!";
    let s2 = "Строка с \"кавычками\" внутри";   // escape-последовательность
    let s3 = "Первая строка\nВторая строка";    // `\n` — перенос

    // Многострочная обычная строка: реальные переводы строки сохраняются:
    let s4 = "Первая строка
Вторая строка
Третья строка";

    // Raw-строки `r"..."` — escape-последовательности НЕ обрабатываются.
    // Удобно для путей Windows, регулярок, HTML и т.п.
    let path   = r"C:\Users\student\file.txt";
    let quotes = r#"Он сказал: "привет""#;    // `r#...#` позволяет включить `"`
    let multi_raw = r#"
Многострочная
raw-строка
"#;

    // ----- Байтовые строки: `&[u8; N]`, не обязаны быть UTF-8 -----
    let bytes_str: &[u8; 5] = b"hello";       // обычная byte string
    let raw_bytes: &[u8; 5] = br"hello";      // raw byte string

    // ----- Логические литералы -----
    let yes: bool = true;
    let no:  bool = false;

    // Печатаем всё, чтобы не было предупреждений о неиспользуемых переменных
    println!("dec={dec}, hex={hex}, oct={oct}, bin={bin}, bc={bc}");
    println!("small={small}, big={big}, unsigned={unsigned}");
    println!("f1={f1}, f2={f2}, f3={f3}, f4={f4}");
    println!("c1={c1}, c2={c2}, c3={:?}, c4={c4}, c5={c5}", c3);
    println!("s1={s1}");
    println!("s2={s2}");
    println!("s3={s3}");
    println!("s4=\n{s4}");
    println!("path={path}");
    println!("quotes={quotes}");
    println!("multi_raw={multi_raw}");
    println!("bytes_str={:?}", std::str::from_utf8(bytes_str).unwrap());
    println!("raw_bytes={:?}", std::str::from_utf8(raw_bytes).unwrap());
    println!("yes={yes}, no={no}");
}

