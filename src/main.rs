//! # Шаблоны (Patterns) в Rust — учебный пример (пункт 1.9)
//!
//! **Шаблон (pattern)** — это синтаксическая конструкция, которая описывает
//! «форму» значения. Шаблоны используются для:
//!   * деструктуризации (`let`, `match`, параметры функций);
//!   * проверки структуры (`match`, `if let`, `while let`);
//!   * связывания переменных с частями значения.
//!
//! Ключевая идея: **шаблон не «вычисляет» значение, а сопоставляется с ним**.
//! В отличие от выражений (п. 1.8), шаблоны бывают **опровержимыми**
//! (refutable — могут не совпасть) и **неопровержимыми** (irrefutable —
//! совпадают всегда).
//!
//! В этом файле разобраны все виды шаблонов:
//!   1. Литеральные шаблоны
//!   2. Шаблоны-идентификаторы и `_`
//!   3. `ref` и `mut` в шаблонах
//!   4. Кортежные шаблоны
//!   5. Шаблоны структур
//!   6. Шаблоны перечислений
//!   7. Шаблоны-диапазоны
//!   8. `@`-связывания
//!   9. Or-шаблоны (`|`)
//!   10. Вложенные шаблоны и rest-паттерны
//!   11. Где можно использовать шаблоны
//!   12. Опровержимые vs неопровержимые шаблоны
//!   13. Шаблоны в параметрах функций
//!   14. Шаблоны в замыканиях

// ============================================================================
// ПОДГОТОВКА: типы для демонстраций
// ============================================================================

#[derive(Debug)]
struct Point {
    x: i32,
    y: i32,
}

#[derive(Debug)]
struct Wrapper(i32, i32);

#[derive(Debug)]
enum Shape {
    Circle { radius: f64 },
    Rectangle { width: f64, height: f64 },
    Triangle(f64, f64, f64),
    Empty,
}

#[derive(Debug)]
enum Message {
    Quit,
    Move { x: i32, y: i32 },
    Write(String),
    ChangeColor(u8, u8, u8),
}

// ============================================================================
// 1. ЛИТЕРАЛЬНЫЕ ШАБЛОНЫ
// ============================================================================
// Литерал в шаблоне совпадает со значением, **равным** этому литералу.
// Это **опровержимый** шаблон: он может не совпасть (кроме случая,
// когда тип имеет ровно одно значение, как unit `()`).

fn literal_patterns_demo() {
    // Совпадение с целым литералом:
    let n = 42;
    match n {
        0 => println!("ноль"),
        42 => println!("сорок два"),
        _ => println!("что-то другое"),
    }

    // Совпадение с отрицательным литералом:
    let temp = -10;
    match temp {
        -10 => println!("очень холодно"),
        0 => println!("ноль градусов"),
        _ => println!("другая температура"),
    }

    // Совпадение с литералом-символом:
    let c = 'R';
    match c {
        'a'..='z' => println!("строчная латинская"),
        'A'..='Z' => println!("заглавная латинская"),
        '0'..='9' => println!("цифра"),
        _ => println!("другой символ"),
    }

    // Совпадение со строковым литералом:
    let s = "hello";
    match s {
        "hello" => println!("приветствие"),
        "bye" => println!("прощание"),
        _ => println!("другое"),
    }

    // Совпадение с bool:
    let flag = true;
    match flag {
        true => println!("истина"),
        false => println!("ложь"),
    }
}

// ============================================================================
// 2. ШАБЛОНЫ-ИДЕНТИФИКАТОРЫ И `_`
// ============================================================================
// **Идентификатор** в шаблоне связывает переменную со значением.
// Идентификатор совпадает **с любым** значением (неопровержимый шаблон).
//
// **`_`** — wildcard-шаблон: совпадает с любым значением и **ничего
// не связывает**. Это удобно, когда значение нужно «пропустить».

fn identifier_and_wildcard_demo() {
    // Идентификатор связывает значение:
    let x = 10;
    match x {
        n => println!("n = {n}"), // `n` совпадает с любым значением
    }

    // `_` игнорирует значение:
    let pair = (1, 2);
    match pair {
        (_, second) => println!("второе значение = {second}"),
    }

    // Разница между `_` и `_name`:
    //   `_` — ничего не связывает, никаких предупреждений;
    //   `_name` — связывает переменную, но компилятор не предупредит
    //            о неиспользовании (это способ «заглушить» warning).
    let value = 42;
    let _ = value;       // игнорируем значение
    let _unused = value; // привязка без предупреждения о неиспользуемости

    // `_` в `let` (иррефутабельный шаблон):
    let (_, y) = (1, 2); // первое значение отброшено
    println!("y = {y}");
}

// ============================================================================
// 3. `REF` И `MUT` В ШАБЛОНАХ
// ============================================================================
// По умолчанию идентификатор в шаблоне **перемещает** или **копирует**
// значение. Чтобы взять ссылку или изменяемую ссылку, используются
// модификаторы:
//   * `ref`     — связывает `&T`;
//   * `ref mut` — связывает `&mut T`;
//   * `mut`     — связывает изменяемую переменную (владение/копия).

fn ref_and_mut_patterns_demo() {
    let string = String::from("hello");

    // `ref` связывает ссылку, не перемещая значение:
    let ref r = string;
    println!("r = {r}, string всё ещё доступен: {string}");

    // `ref mut` связывает изменяемую ссылку:
    let mut number = 10;
    {
        let ref mut rm = number;
        *rm += 5;
    }
    println!("number = {number}"); // 15

    // `mut` в шаблоне делает связанную переменную изменяемой:
    let pair = (1, 2);
    let (mut a, b) = pair;
    a += 100;
    println!("a = {a}, b = {b}");

    // Деструктуризация с `ref` (без перемещения полей):
    #[derive(Debug)]
    struct Name {
        first: String,
        last: String,
    }
    let name = Name {
        first: "Ivan".to_string(),
        last: "Petrov".to_string(),
    };
    let Name { ref first, ref last } = name;
    println!("first = {first}, last = {last}");
    println!("name всё ещё доступен: {:?}", name);

    // Синтаксический сахар: `&x` в шаблоне эквивалентно `ref x`,
    // но с «разыменованием» — используется при сопоставлении ссылок:
    let value = 5;
    let reference = &value;
    match reference {
        &v => println!("разыменовали ссылку, v = {v}"),
    }
}

// ============================================================================
// 4. КОРТЕЖНЫЕ ШАБЛОНЫ
// ============================================================================
// `(a, b, c)` — деструктурирует кортеж из N элементов.
// `(a,)` — кортеж из одного элемента (запятая обязательна).
// `()` — unit, единственное значение типа `()`.

fn tuple_patterns_demo() {
    // Деструктуризация кортежа:
    let tuple = (1, "два", 3.0);
    let (a, b, c) = tuple;
    println!("a = {a}, b = {b}, c = {c}");

    // Вложенные кортежи:
    let nested = ((1, 2), (3, 4));
    let ((x1, x2), (y1, y2)) = nested;
    println!("x1 = {x1}, x2 = {x2}, y1 = {y1}, y2 = {y2}");

    // Игнорирование части кортежа:
    let (first, _, third) = (10, 20, 30);
    println!("first = {first}, third = {third}");

    // Кортеж из одного элемента:
    let (single,) = (42,);
    println!("single = {single}");

    // Unit-паттерн:
    let () = ();
    println!("unit совпал");
}

// ============================================================================
// 5. ШАБЛОНЫ СТРУКТУР
// ============================================================================
// Для структур с именованными полями:
//   `Point { x, y }`         — сокращённая запись (связывает `x`, `y`);
//   `Point { x: a, y: b }`   — полные имена;
//   `Point { x, .. }`        — игнорировать остальные поля.
//
// Для кортежных структур:
//   `Wrapper(a, b)` — деструктурирует позиционно.

fn struct_patterns_demo() {
    let p = Point { x: 3, y: 4 };

    // Сокращённая запись (поля `x` и `y` связываются с одноимёнными переменными):
    let Point { x, y } = p;
    println!("x = {x}, y = {y}");

    // Полная запись с переименованием:
    let Point { x: a, y: b } = Point { x: 10, y: 20 };
    println!("a = {a}, b = {b}");

    // Игнорирование полей через `..`:
    let Point { y, .. } = Point { x: 1, y: 2 };
    println!("y = {y}");

    // Кортежная структура:
    let Wrapper(first, second) = Wrapper(100, 200);
    println!("first = {first}, second = {second}");

    // Вложенная структура в `match`:
    let maybe_point = Some(Point { x: 7, y: 8 });
    match maybe_point {
        Some(Point { x: 0, y: 0 }) => println!("в начале координат"),
        Some(Point { x, y }) => println!("точка ({x}, {y})"),
        None => println!("нет точки"),
    }
}

// ============================================================================
// 6. ШАБЛОНЫ ПЕРЕЧИСЛЕНИЙ
// ============================================================================
// Каждый вариант перечисления — свой шаблон:
//   `Shape::Circle { radius }`   — вариант с именованными полями;
//   `Shape::Triangle(a, b, c)`   — кортежный вариант;
//   `Shape::Empty`               — unit-вариант.

fn enum_patterns_demo() {
    let shapes = [
        Shape::Circle { radius: 1.0 },
        Shape::Rectangle { width: 2.0, height: 3.0 },
        Shape::Triangle(3.0, 4.0, 5.0),
        Shape::Empty,
    ];

    for shape in &shapes {
        // `match` по вариантам перечисления:
        match shape {
            Shape::Circle { radius } => println!("круг радиуса {radius}"),
            Shape::Rectangle { width, height } => {
                println!("прямоугольник {width}×{height}")
            }
            Shape::Triangle(a, b, c) => println!("треугольник ({a}, {b}, {c})"),
            Shape::Empty => println!("пустая фигура"),
        }
    }

    // Деструктуризация enum через `let` — только для одного варианта
    // (irrefutable pattern); на практике чаще используют `if let`.
    let msg = Message::Move { x: 10, y: 20 };
    if let Message::Move { x, y } = msg {
        println!("Move: x = {x}, y = {y}");
    }
}

// ============================================================================
// 7. ШАБЛОНЫ-ДИАПАЗОНЫ
// ============================================================================
// `a..b`   — полуоткрытый диапазон (`a <= x < b`), **устарел** в шаблонах;
// `a..=b`  — включающий диапазон (`a <= x <= b`);
// `..b`    — до `b` не включительно;
// `a..`    — от `a` включительно.
//
// В `match` допустимы только диапазоны с **константными** границами.

fn range_patterns_demo() {
    // Диапазон в `match`:
    for n in [-1, 0, 5, 10, 42, 100] {
        match n {
            i32::MIN..=-1 => println!("{n}: отрицательное"),
            0 => println!("{n}: ноль"),
            1..=9 => println!("{n}: цифра"),
            10..=99 => println!("{n}: двузначное"),
            _ => println!("{n}: большое"),
        }
    }

    // Диапазон в `if let`:
    let temp = 25;
    if let 20..=30 = temp {
        println!("комфортная температура: {temp}");
    }

    // Диапазон с char:
    let c = 'R';
    if let 'A'..='Z' = c {
        println!("'{c}' — заглавная буква");
    }
}

// ============================================================================
// 8. `@`-СВЯЗЫВАНИЯ
// ============================================================================
// `name @ pattern` — одновременно **проверяет** соответствие pattern'у
// и **связывает** всё значение с `name`. Удобно, когда нужен
// и сам объект, и его проверка.

fn at_binding_demo() {
    let n = 15;

    // Связываем значение с `x` и проверяем, что оно в диапазоне:
    match n {
        x @ 1..=9 => println!("x = {x} — однозначное"),
        x @ 10..=99 => println!("x = {x} — двузначное"),
        x => println!("x = {x} — большое"),
    }

    // `@` в сочетании с enum:
    let msg = Message::ChangeColor(255, 128, 0);
    match msg {
        Message::ChangeColor(r @ 0..=255, g @ 0..=255, b @ 0..=255) => {
            println!("цвет RGB({r}, {g}, {b})")
        }
        Message::ChangeColor(..) => println!("некорректный цвет"),
        _ => println!("другое сообщение"),
    }

    // `@` в деструктуризации:
    let pair = (1, 2);
    match pair {
        whole @ (x, y) => println!("whole = {whole:?}, x = {x}, y = {y}"),
    }
}

// ============================================================================
// 9. OR-ШАБЛОНЫ (`|`)
// ============================================================================
// `pattern1 | pattern2 | ...` — совпадает, если совпадает **хотя бы один**
// из шаблонов. Часто используется с `match`.
//
// Требование: все альтернативы должны связывать **одинаковый набор
// переменных с одинаковыми типами**.

fn or_patterns_demo() {
    // Простой or:
    let n = 3;
    match n {
        1 | 2 | 3 => println!("маленькое число"),
        4 | 5 | 6 => println!("среднее число"),
        _ => println!("другое"),
    }

    // Or с диапазонами:
    let c = 'x';
    match c {
        'a'..='z' | 'A'..='Z' => println!("буква"),
        '0'..='9' => println!("цифра"),
        _ => println!("прочее"),
    }

    // Or, связывающий переменные (должны совпадать имена и типы):
    let value = Some(10);
    match value {
        Some(x) => println!("Some(x) = {x}"),
        None => println!("None"),
    }

    // Or в `if let`:
    let answer = "yes";
    if let "yes" | "y" | "да" = answer {
        println!("согласие: {answer}");
    }
}

// ============================================================================
// 10. ВЛОЖЕННЫЕ ШАБЛОНЫ И REST-ПАТТЕРНЫ
// ============================================================================
// `..` в шаблоне означает «остальное»:
//   * в структуре — игнорировать остальные поля;
//   * в кортеже — игнорировать оставшиеся элементы;
//   * в срезе — «остальные элементы среза».

fn nested_and_rest_demo() {
    // `..` в структуре:
    let p = Point { x: 1, y: 2 };
    let Point { x, .. } = p;
    println!("x = {x}");

    // `..` в кортеже:
    let tuple = (1, 2, 3, 4, 5);
    let (first, .., last) = tuple;
    println!("first = {first}, last = {last}");

    // `..` в `match` по срезу с фиксированными краями:
    let slice: &[i32] = &[10, 20, 30, 40, 50];
    match slice {
        [1, rest @ ..] => println!("начинается с 1, остальное = {rest:?}"),
        [first, .., 50] => println!("заканчивается на 50, первое = {first}"),
        _ => println!("другое"),
    }

    // Вложенные шаблоны:
    let complex = Some((1, 'a', Point { x: 10, y: 20 }));
    match complex {
        Some((n, c, Point { x, y })) if n > 0 => {
            println!("n = {n}, c = {c}, точка ({x}, {y})")
        }
        _ => println!("не совпало"),
    }
}

// ============================================================================
// 11. ГДЕ МОЖНО ИСПОЛЬЗОВАТЬ ШАБЛОНЫ
// ============================================================================
// Шаблоны допустимы в следующих позициях:
//   * `let PATTERN = expr;`
//   * параметры функций и замыканий
//   * `match expr { PATTERN => ... }`
//   * `if let PATTERN = expr`
//   * `while let PATTERN = expr`
//   * `for PATTERN in iter`
//   * `let-else` — `let PATTERN = expr else { ... };`

fn pattern_positions_demo() {
    // В `let`:
    let (a, b) = (1, 2);
    println!("a = {a}, b = {b}");

    // В параметрах функции (см. `takes_point` ниже):
    takes_point(Point { x: 5, y: 5 });

    // В `if let`:
    let maybe = Some(42);
    if let Some(x) = maybe {
        println!("Some(x) = {x}");
    }

    // В `while let`:
    let mut stack = vec![1, 2, 3];
    while let Some(top) = stack.pop() {
        println!("pop = {top}");
    }

    // В `for`:
    let pairs = [(1, 'a'), (2, 'b')];
    for (n, c) in pairs {
        println!("n = {n}, c = {c}");
    }

    // `let-else` (стабильно с Rust 1.65):
    let maybe_number: Option<i32> = Some(7);
    let Some(n) = maybe_number else {
        println!("не число");
        return;
    };
    println!("let-else: n = {n}");
}

fn takes_point(Point { x, y }: Point) {
    println!("takes_point: x = {x}, y = {y}");
}

// ============================================================================
// 12. ОПРОВЕРЖИМЫЕ VS НЕОПРОВЕРЖИМЫЕ ШАБЛОНЫ
// ============================================================================
// **Неопровержимый (irrefutable)** шаблон всегда совпадает с любым
// значением данного типа: `x`, `_`, `(a, b)`, `Point { x, y }`,
// если тип значения совпадает.
//
// **Опровержимый (refutable)** шаблон может не совпасть:
// `Some(x)`, `0..=9`, `Shape::Circle { .. }`.
//
// Требования:
//   * в `let`, параметрах функций, `for` — только **неопровержимые**;
//   * в `match`, `if let`, `while let` — можно **оба вида**.
//     (В `match` хотя бы одна ветвь должна покрывать всё.)

fn refutability_demo() {
    // Irrefutable: `let`
    let (a, b) = (1, 2); // всегда совпадёт
    let Point { x, y } = Point { x: 3, y: 4 };
    let _ = a + b + x + y;

    // Refutable в `let` — ошибка компиляции:
    // let Some(n) = Some(1); // ошибка: refutable pattern in local binding

    // Refutable в `if let` — норма:
    let value: Option<i32> = Some(5);
    if let Some(n) = value {
        println!("n = {n}");
    }

    // Refutable в `match` — норма:
    match value {
        Some(n) if n > 0 => println!("положительное {n}"),
        Some(_) => println!("не положительное"),
        None => println!("None"),
    }
}

// ============================================================================
// 13. ШАБЛОНЫ В ПАРАМЕТРАХ ФУНКЦИЙ
// ============================================================================
// В параметрах функции разрешены **только неопровержимые** шаблоны.
// Если нужен опровержимый — используйте `match` внутри функции.

// Irrefutable:
fn tuple_arg((a, b): (i32, i32)) -> i32 {
    a + b
}

fn point_arg(Point { x, y }: Point) -> i32 {
    x * y
}

// Refutable в параметрах — ошибка, поэтому делаем через `match`:
fn option_arg(value: Option<i32>) -> i32 {
    match value {
        Some(n) => n,
        None => 0,
    }
}

fn function_patterns_demo() {
    println!("tuple_arg((3, 4)) = {}", tuple_arg((3, 4)));
    println!("point_arg(Point {{x: 5, y: 6}}) = {}", point_arg(Point { x: 5, y: 6 }));
    println!("option_arg(Some(42)) = {}", option_arg(Some(42)));
    println!("option_arg(None) = {}", option_arg(None));
}

// ============================================================================
// 14. ШАБЛОНЫ В ЗАМЫКАНИЯХ
// ============================================================================
// Параметры замыканий подчиняются тем же правилам, что и функции:
// только неопровержимые шаблоны.

fn closure_patterns_demo() {
    // Irrefutable pattern в аргументе:
    let sum_tuple = |(a, b): (i32, i32)| a + b;
    println!("sum_tuple((2, 3)) = {}", sum_tuple((2, 3)));

    // Разбор структуры в замыкании:
    let area = |Point { x, y }: Point| (x * y) as f64;
    println!("area(Point {{x: 3, y: 4}}) = {}", area(Point { x: 3, y: 4 }));

    // Refutable шаблон в замыкании — ошибка:
    // let f = |Some(n): Option<i32>| n; // ошибка: refutable pattern
}

