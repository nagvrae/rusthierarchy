// ============================================================================
// 1. СКАЛЯРНЫЕ ТИПЫ
// ============================================================================
// Скалярный тип хранит **одно** значение. В Rust четыре группы скаляров:
// целые, вещественные, `bool` и `char`. По умолчанию целое — `i32`,
// вещественное — `f64`. Тип можно указывать аннотацией (`let x: i32`)
// или суффиксом литерала (`5i32`).

fn scalar_types_demo() {
    // ----- Логический тип -----
    let flag: bool = true;
    let also_flag = false; // тип выведен как `bool`
    println!("flag = {flag}, also_flag = {also_flag}");

    // ----- Целые числа -----
    // Знаковые: i8, i16, i32, i64, i128, isize
    // Беззнаковые: u8, u16, u32, u64, u128, usize
    // `isize`/`usize` — размер указателя на текущей платформе.
    let small: i8 = -128;
    let unsigned: u32 = 4_000_000_000;
    let default_int = 42; // по умолчанию `i32`
    let pointer_sized: usize = 1024; // обычно 64-битный
    println!("small = {small}, unsigned = {unsigned}");
    println!("default_int (i32) = {default_int}, pointer_sized (usize) = {pointer_sized}");

    // ----- Вещественные числа -----
    // `f32` (4 байта) и `f64` (8 байт). По умолчанию — `f64`.
    let single: f32 = 3.14;
    let double = 2.718_281_828; // `f64`
    println!("single (f32) = {single}, double (f64) = {double}");

    // ----- Символьный тип -----
    // `char` — 4 байта, хранит **Unicode scalar value**,
    // а не просто байт, как в C.
    let letter: char = 'R';
    let cyrillic = 'я';
    let emoji = '😀';
    println!("letter = {letter}, cyrillic = {cyrillic}, emoji = {emoji}");
}

// ============================================================================
// 2. СТРОКОВЫЕ ТИПЫ: `str` И `String`
// ============================================================================
// `str` — **DST** (см. раздел 13): срез строки, всегда используется
// за ссылкой: `&str`. Строковые литералы (`"hello"`) имеют тип `&'static str`.
// `String` — владеемая, изменяемая строка в куче (не DST, имеет размер).

fn string_types_demo() {
    // `&str` — заимствованный срез строки.
    let borrowed: &str = "привет";
    // `String` — владеемая строка.
    let owned: String = String::from("мир");
    // Срез `String` тоже имеет тип `&str`.
    let slice: &str = &owned;

    println!("borrowed: {borrowed}");
    println!("owned: {owned}");
    println!("slice: {slice}");
    println!("borrowed.len() = {}", borrowed.len());
}

// ============================================================================
// 3. NEVER-ТИП (`!`)
// ============================================================================
// `!` — тип **без значений**. Он обозначает вычисление, которое
// **никогда не завершается нормально**: паника, `return`, `break`,
// `continue`, бесконечный цикл. Функция с возвращаемым типом `!`
// называется **дивергентной**.
//
// `!` может быть приведён к любому другому типу — это позволяет
// использовать, например, `panic!` в `match` там, где ожидается значение.

fn diverging_function() -> ! {
    // Эта функция никогда не возвращает управление вызывающему коду.
    panic!("эта функция никогда не вернётся");
}

fn never_type_demo() {
    let n = 0;
    // `panic!` имеет тип `!`, поэтому подходит в любую ветвь `match`.
    let _value: i32 = match n {
        0 => 42,
        _ => panic!("не ноль"), // тип `!` совместим с `i32`
    };

    // Бесконечный цикл `loop` без `break` тоже имеет тип `!`.
    // (Здесь не запускаем, чтобы не заблокировать программу.)
    // let _forever: ! = loop {};
}

// ============================================================================
// 4. СОСТАВНЫЕ ТИПЫ: КОРТЕЖИ, МАССИВЫ, СРЕЗЫ
// ============================================================================

/// Демонстрация кортежей, массивов и срезов.
fn compound_types_demo() {
    // ----- Кортеж -----
    // `(T1, T2, ...)` — фиксированная последовательность значений
    // **разных** типов. Доступ по индексу: `.0`, `.1` и т.д.
    let tuple: (i32, bool, char) = (42, true, 'R');
    println!("tuple = {:?}", tuple);
    println!("tuple.0 = {}, tuple.1 = {}, tuple.2 = {}", tuple.0, tuple.1, tuple.2);

    // Деструктуризация кортежа:
    let (number, flag, letter) = tuple;
    println!("number = {number}, flag = {flag}, letter = {letter}");

    // ----- Массив -----
    // `[T; N]` — **фиксированная** длина `N`, известная на этапе компиляции.
    // Все элементы одного типа. Хранится на стеке (если не в куче).
    let array: [i32; 5] = [1, 2, 3, 4, 5];
    println!("array = {:?}, длина = {}", array, array.len());

    // Массив из повторяющегося значения:
    let zeros = [0u8; 4]; // [0, 0, 0, 0]
    println!("zeros = {:?}", zeros);

    // ----- Срез -----
    // `[T]` — **DST**: «вид» на непрерывную последовательность элементов.
    // Всегда используется за ссылкой: `&[T]` или `&mut [T]`.
    // Срез может указывать на часть массива или `Vec`.
    let slice: &[i32] = &array[1..4]; // элементы с индексами 1, 2, 3
    println!("slice = {:?}, длина = {}", slice, slice.len());

    // Срез можно получить и из `Vec`:
    let vec = vec![10, 20, 30, 40];
    let vec_slice: &[i32] = &vec[..2];
    println!("vec_slice = {:?}", vec_slice);
}

