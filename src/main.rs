//! # Выражения (Expressions) в Rust — учебный пример (пункт 1.8)
//!
//! Этот файл завершает обзор базового синтаксиса. Если пункты 1.1–1.7
//! описывали «из чего состоит» программа, то здесь мы смотрим, **как
//! из этого строится вычисление**.
//!
//! Ключевая идея Rust: язык **ориентирован на выражения** (expression-oriented).
//! Почти всё, что «что-то делает», является выражением и **возвращает значение**:
//! литерал, вызов функции, блок `{ ... }`, `if`, `match`, `loop` и даже `return`.
//!
//! В этом файле разобраны:
//!   1. Выражения vs операторы (statements)
//!   2. Блочные выражения и хвостовое выражение
//!   3. Литеральные, путевые и сгруппированные выражения
//!   4. Операторные выражения
//!   5. Кортежные и индексные выражения
//!   6. Структурные выражения
//!   7. Вызовы функций и методов
//!   8. Доступ к полям
//!   9. Замыкания
//!  10. Циклы (`loop`, `while`, `for`) как выражения
//!  11. `if` и `match` как выражения
//!  12. `return`, `break`, `continue`
//!  13. `await` и `async` блоки
//!  14. `_` выражения (underscore expressions)
//!  15. `unsafe` и `const` блоки
//!
//! **Главное правило:** точка с запятой `;` превращает выражение в
//! **оператор-выражение** и **отбрасывает** его значение. Если в конце
//! блока стоит выражение **без** `;`, его значение становится значением
//! всего блока[reference:0].

// ============================================================================
// 1. ВЫРАЖЕНИЯ VS ОПЕРАТОРЫ
// ============================================================================
// **Оператор (statement)** выполняет действие и **не производит значения**
// для окружающего контекста. Примеры: `let x = 5;`, объявление элемента
// (`fn`, `struct`), `use`.
//
// **Выражение (expression)** вычисляется и **производит значение**:
// литерал `42`, `a + b`, вызов функции `f()`, блок `{ ... }`,
// `if ... { ... } else { ... }`, `match`, `loop` и т.д.[reference:1].
//
// Именно поэтому `let` — оператор, а не выражение: у `let` нет значения,
// его нельзя присвоить другой переменной. Следующая строка **не**
// скомпилируется:
//
//     let value = (let x = 3); // ошибка: `let` не производит значение

/// Демонстрация того, что `let` — оператор, а блок — выражение.
fn expressions_vs_statements() {
    // `let` — оператор.
    let x = 10;

    // Блок `{ ... }` — выражение. Его значение — результат последнего
    // выражения без `;` (хвостового выражения).
    let y = {
        let inner = 5;
        inner * 2 // хвостовое выражение: значение блока = 10
    };

    println!("x = {x}, y = {y}");

    // Если поставить `;` после `inner * 2`, блок вернёт `()`,
    // и `let y: i32 = { ... };` перестанет компилироваться.
}

// ============================================================================
// 2. БЛОЧНЫЕ ВЫРАЖЕНИЯ И ХВОСТОВОЕ ВЫРАЖЕНИЕ
// ============================================================================
// Блок `{ ... }` — это выражение, которое:
//   * выполняется последовательно, оператор за оператором;
//   * возвращает значение **последнего выражения без `;`**
//     (tail expression);
//   * если хвостового выражения нет (или после него стоит `;`),
//     возвращает `()` (unit)[reference:2].
//
// Это фундаментальное отличие от C-подобных языков, где `{}` — просто
// группировка операторов.

fn block_expression_demo() -> i32 {
    // Блок как инициализатор:
    let value = {
        let a = 2;
        let b = 3;
        a + b // значение блока — 5
    };

    // Блок без хвостового выражения возвращает `()`:
    let unit: () = {
        1 + 1; // `;` отбрасывает значение 2
    };

    // Функция возвращает результат хвостового выражения:
    value * 10 // 50
}

// ============================================================================
// 3. ЛИТЕРАЛЬНЫЕ, ПУТЕВЫЕ И СГРУППИРОВАННЫЕ ВЫРАЖЕНИЯ
// ============================================================================
// **Литеральное выражение** — просто литерал: `42`, `"hello"`, `true`.
// **Путевое выражение** — путь к элементу: `std::f64::consts::PI`,
// `Rectangle::new`, `self.value`.
// **Сгруппированное выражение** — выражение в скобках `( ... )`,
// меняет приоритет вычислений.

const TWO: i32 = 2;

fn literal_path_grouped_demo() {
    // Литеральные выражения:
    let literal = 100;

    // Путевые выражения:
    let pi = std::f64::consts::PI;   // путь к константе
    let two = TWO;                    // путь к константе в текущем модуле
    let abs = i32::abs;               // путь к ассоциированной функции

    // Сгруппированное выражение меняет порядок вычислений:
    let without_group = 2 + 3 * 4;       // 14
    let with_group = (2 + 3) * 4;        // 20

    println!("literal = {literal}");
    println!("pi = {pi}, two = {two}, abs(-5) = {}", abs(-5));
    println!("2 + 3 * 4 = {without_group}; (2 + 3) * 4 = {with_group}");
}

// ============================================================================
// 4. ОПЕРАТОРНЫЕ ВЫРАЖЕНИЯ
// ============================================================================
// Это выражения, построенные вокруг операторов: `a + b`, `-x`, `!flag`,
// `a && b`, `a as u8`, `&value`, `*ptr` и т.д.
// Подробно операторы разбирались в п. 1.6; здесь важно запомнить,
// что **любой оператор возвращает значение** и может быть частью
// более крупного выражения.

fn operator_expressions_demo() {
    let a = 10;
    let b = 3;

    // Арифметическое выражение как часть большего:
    let result = (a * b) + (a % b); // 30 + 1 = 31
    println!("(a * b) + (a % b) = {result}");

    // Логическое выражение:
    let cond = a > b && b > 0;
    println!("a > b && b > 0 = {cond}");

    // Приведение типа (`as`) — тоже выражение:
    let float_value = 42 as f64 / 2.0;
    println!("42 as f64 / 2.0 = {float_value}");

    // Ссылка и разыменование:
    let x = 7;
    let r = &x;
    let deref = *r + 1;
    println!("*&x + 1 = {deref}");
}

// ============================================================================
// 5. КОРТЕЖНЫЕ И ИНДЕКСНЫЕ ВЫРАЖЕНИЯ
// ============================================================================
// **Кортежное выражение** — `(a, b, c)` или `(a,)` (кортеж из одного элемента;
// запятая обязательна).
// **Индексное выражение** — `array[i]`, `slice[i]`, `vec[i]`.

fn tuple_and_index_demo() {
    // Кортежные выражения:
    let pair = (1, "два");
    let single = (42,); // кортеж из одного элемента
    let unit = (); // unit-тип, кортеж из нуля элементов

    println!("pair = {pair:?}, single = {single:?}, unit = {unit:?}");

    // Индексные выражения:
    let array = [10, 20, 30, 40];
    let slice = &array[1..3];

    println!("array[0] = {}", array[0]);
    println!("slice[0] = {}", slice[0]);

    // Индексное выражение возвращает значение элемента:
    let second = array[1]; // 20
    println!("second = {second}");
}

// ============================================================================
// 6. СТРУКТУРНЫЕ ВЫРАЖЕНИЯ
// ============================================================================
// Выражение, создающее значение структуры, перечисления или union:
// `Point { x: 1, y: 2 }`, `Shape::Circle(2.0)`, `Message::Move { x: 10, y: 20 }`.
// Это **выражение**, потому что оно производит значение.

#[derive(Debug)]
struct Point {
    x: i32,
    y: i32,
}

#[derive(Debug)]
enum Shape {
    Circle(f64),
    Rectangle { width: f64, height: f64 },
}

fn struct_expression_demo() {
    // Структурное выражение:
    let p = Point { x: 3, y: 4 };
    println!("p = {p:?}");

    // Выражение варианта перечисления:
    let circle = Shape::Circle(2.0);
    let rect = Shape::Rectangle { width: 3.0, height: 4.0 };
    println!("circle = {circle:?}, rect = {rect:?}");

    // Структурное выражение можно использовать как аргумент:
    print_point(Point { x: 10, y: 20 });
}

fn print_point(p: Point) {
    println!("point: {p:?}");
}

// ============================================================================
// 7. ВЫЗОВЫ ФУНКЦИЙ И МЕТОДОВ
// ============================================================================
// **Вызов функции**: `f(a, b)`, `std::mem::size_of::<i32>()`.
// **Вызов метода**: `receiver.method(args)`, `vec.push(1)`.
// Оба — выражения, возвращающие значение (возможно, `()`).

fn add(a: i32, b: i32) -> i32 {
    a + b
}

struct Calculator {
    value: i32,
}

impl Calculator {
    fn new() -> Self {
        Self { value: 0 }
    }

    fn add(&mut self, n: i32) -> i32 {
        self.value += n;
        self.value
    }
}

fn call_expressions_demo() {
    // Вызов функции:
    let sum = add(2, 3);
    println!("add(2, 3) = {sum}");

    // Вызов метода:
    let mut calc = Calculator::new();
    let after_add = calc.add(10);
    println!("calc.add(10) = {after_add}");

    // Вызов функции как часть большего выражения:
    let combined = add(1, 2) * add(3, 4);
    println!("add(1, 2) * add(3, 4) = {combined}");
}

// ============================================================================
// 8. ДОСТУП К ПОЛЯМ
// ============================================================================
// `expr.field` — выражение доступа к полю структуры.
// `expr.0`, `expr.1` — доступ к полю кортежа или кортежной структуры.

#[derive(Debug)]
struct Wrapper(i32, i32);

fn field_access_demo() {
    let p = Point { x: 5, y: 6 };

    // Доступ к полю структуры:
    let px = p.x;
    println!("p.x = {px}");

    // Доступ к полю кортежной структуры:
    let w = Wrapper(10, 20);
    println!("w.0 = {}, w.1 = {}", w.0, w.1);

    // Доступ к полю в выражении:
    let sum = p.x + p.y; // 11
    println!("p.x + p.y = {sum}");
}

// ============================================================================
// 9. ЗАМЫКАНИЯ
// ============================================================================
// Замыкание — анонимная функция, которую можно хранить в переменной
// и вызывать. Синтаксис: `|args| body`.
// Тело замыкания — выражение (или блок).

fn closure_expressions_demo() {
    // Замыкание с одним выражением:
    let double = |x: i32| x * 2;
    println!("double(21) = {}", double(21));

    // Замыкание с блоком:
    let add_and_print = |a: i32, b: i32| {
        let result = a + b;
        println!("closure result = {result}");
        result
    };
    let r = add_and_print(3, 4);
    println!("closure returned {r}");

    // Замыкание, захватывающее окружение:
    let offset = 100;
    let shifted = |x: i32| x + offset; // захват `offset` по ссылке
    println!("shifted(1) = {}", shifted(1));
}

// ============================================================================
// 10. ЦИКЛЫ КАК ВЫРАЖЕНИЯ
// ============================================================================
// `loop` — **выражение**, которое возвращает значение, переданное в `break`.
// `while` и `for` — тоже выражения, но они всегда возвращают `()`.

fn loop_expressions_demo() {
    // `loop` с возвратом значения:
    let mut counter = 0;
    let result = loop {
        counter += 1;
        if counter == 5 {
            break counter * 10; // значение всего `loop`
        }
    };
    println!("loop returned {result}");

    // `while` возвращает `()`:
    let mut n = 3;
    let while_result: () = while n > 0 {
        n -= 1;
    };
    println!("while result = {while_result:?}, n = {n}");

    // `for` тоже возвращает `()`:
    let for_result: () = for i in 1..=3 {
        println!("for i = {i}");
    };
    println!("for result = {for_result:?}");
}

// ============================================================================
// 11. `IF` И `MATCH` КАК ВЫРАЖЕНИЯ
// ============================================================================
// В Rust `if` и `match` — **выражения**. Если все ветви возвращают
// значение одного типа, всё выражение производит это значение.
// `if` без `else` возвращает `()`.

fn if_and_match_expressions_demo() {
    let n = 5;

    // `if` как выражение:
    let parity = if n % 2 == 0 { "чётное" } else { "нечётное" };
    println!("n = {n}, {parity}");

    // `if` без `else` возвращает `()`:
    let unit: () = if n > 0 { println!("n положительное") };
    println!("if without else = {unit:?}");

    // `match` как выражение:
    let description = match n {
        0 => "ноль",
        1..=9 => "цифра",
        _ => "много",
    };
    println!("match: {description}");

    // Ветви `match` тоже могут содержать блоки с хвостовыми выражениями:
    let computed = match n {
        0 => 0,
        x if x > 0 => {
            let squared = x * x;
            squared + 1 // значение ветви
        }
        _ => -1,
    };
    println!("computed = {computed}");
}

// ============================================================================
// 12. `RETURN`, `BREAK`, `CONTINUE`
// ============================================================================
// Все три — **выражения с типом `!`** (never type): они прерывают
// нормальное вычисление и не возвращают значение в обычном смысле.
// Благодаря типу `!` их можно использовать там, где ожидается
// значение любого другого типа.

fn return_expression_demo(x: i32) -> i32 {
    // `return` — выражение. Его можно использовать в позиции выражения,
    // хотя на практике чаще пишут просто `return x;`.
    if x < 0 {
        return 0; // ранний выход
    }

    // Хвостовое выражение:
    x * 2
}

fn break_continue_demo() {
    for i in 0..5 {
        if i == 2 {
            continue; // выражение `!`
        }
        if i == 4 {
            break; // выражение `!`
        }
        println!("i = {i}");
    }
}

// ============================================================================
// 13. `AWAIT` И `ASYNC` БЛОКИ
// ============================================================================
// `.await` — постфиксное выражение, допустимое только в **асинхронном
// контексте** (`async fn`, `async {}`). Оно приостанавливает выполнение
// до готовности future и возвращает его результат.
//
// `async { ... }` и `async move { ... }` — выражения, создающие future.
// Сами по себе они не выполняются: нужен executor.

use std::future::Future;
use std::pin::Pin;
use std::task::{Context, Poll};

/// Простейший future, который сразу готов.
struct ReadyFuture(i32);

impl Future for ReadyFuture {
    type Output = i32;

    fn poll(self: Pin<&mut Self>, _cx: &mut Context<'_>) -> Poll<Self::Output> {
        Poll::Ready(self.0)
    }
}

/// Асинхронная функция: внутри неё `.await` легален.
async fn async_add(a: i32, b: i32) -> i32 {
    let ready = ReadyFuture(a).await; // `.await` expression
    ready + b
}

/// Демонстрация синтаксиса. Чтобы реально выполнить future,
/// нужен executor (например, `futures::executor::block_on`).
fn await_expression_demo() {
    // `async` блок — выражение типа `impl Future`:
    let _future = async {
        let x = ReadyFuture(10).await;
        x + 5
    };

    // `async move` захватывает окружение по значению:
    let value = 42;
    let _moved = async move { value };

    // Асинхронная функция тоже возвращает future:
    let _add_future = async_add(2, 3);

    println!("await/async выражения созданы (future не выполнен)");
}

// ============================================================================
// 14. `_` ВЫРАЖЕНИЯ (UNDERSCORE EXPRESSIONS)
// ============================================================================
// `_` как выражение допустимо **только в левой части присваивания
// с деструктуризацией**. Оно означает «вычислить и отбросить»,
// явно показывая намерение.
// Это отличается от wildcard-шаблона `_` в `match` или `let`.

fn underscore_expression_demo() {
    // Деструктурирующее присваивание с `_`:
    let pair = (1, 2);
    let mut a = 0;
    (_, a) = pair; // первое значение отброшено
    println!("a = {a}"); // 2

    // `_` в деструктуризации структуры:
    struct Position {
        x: u32,
        y: u32,
    }
    let pos = Position { x: 10, y: 20 };
    let x_value;
    Position { x: x_value, y: _ } = pos; // y отброшен
    println!("x_value = {x_value}");

    // `_ = expr;` явно отбрасывает результат и подавляет `unused_must_use`:
    _ = 2 + 2;
    println!("underscore expression выполнено");
}

// ============================================================================
// 15. `UNSAFE` И `CONST` БЛОКИ
// ============================================================================
// `unsafe { ... }` — блок, внутри которого разрешены опасные операции
// (разыменование сырых указателей, вызов `unsafe fn` и т.д.).
// Это **выражение**: он возвращает значение последнего выражения.
//
// `const { ... }` — блок, вычисляемый на этапе компиляции в константном
// контексте. Тоже выражение.

fn unsafe_and_const_blocks_demo() {
    let x = 42;
    let ptr = &x as *const i32;

    // `unsafe` блок как выражение:
    let value = unsafe { *ptr };
    println!("unsafe deref = {value}");

    // `const` блок как выражение (стабильно с Rust 1.79):
    let computed = const {
        let a = 2;
        let b = 3;
        a * b
    };
    println!("const block = {computed}");
}

