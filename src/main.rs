// Мы уже разбирали объявления в п. 1.4; здесь — именно **типы**,
// которые эти объявления создают.

/// Структура с именованными полями — тип `Point`.
#[derive(Debug)]
struct Point {
    x: f64,
    y: f64,
}

/// Кортежная структура — тип `Meters`.
#[derive(Debug)]
struct Meters(f64);

/// Unit-структура — тип `Marker` (ZST, см. раздел 13).
#[derive(Debug)]
struct Marker;

/// Перечисление — тип `Message`, который может быть одним из вариантов.
#[derive(Debug)]
enum Message {
    Quit,
    Move { x: i32, y: i32 },
    Write(String),
    ChangeColor(u8, u8, u8),
}

fn struct_enum_types_demo() {
    let p: Point = Point { x: 1.0, y: 2.0 };
    let m: Meters = Meters(42.0);
    let _marker: Marker = Marker;

    println!("p = {:?}", p);
    println!("m = {:?}", m);
    println!("marker = {:?}", _marker);

    let msg: Message = Message::Move { x: 10, y: 20 };
    println!("msg = {:?}", msg);
}

