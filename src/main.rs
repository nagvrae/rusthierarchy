//! В этом файле разобраны все основные группы операторов языка:
//!   1. Арифметические операторы
//!   2. Операторы сравнения
//!   3. Логические операторы (короткое замыкание)
//!   4. Побитовые операторы
//!   5. Оператор присваивания и составные присваивания
//!   6. Операторы доступа: поле, вызов метода, индексация, вызов функции
//!   7. Приведение типов (`as`)
//!   8. Оператор проброса ошибки (`?`)
//!   9. Диапазоны (`..`, `..=`)
//!  10. Специальные символы и пунктуация (`@`, `::`, `:`, `;`, `->`, `_` и др.)
//!  11. Приоритет операторов
//!  12. Перегрузка операторов через трейты
//!
//! Многие операторы в Rust — это **синтаксический сахар** над вызовами
//! методов трейтов. Например, `a + b` превращается в `a.add(b)`.
//! Такие операторы можно перегружать для собственных типов (раздел 12).

use std::ops::{Add, Neg, Not};
use std::fmt;

// ============================================================================
// 1. АРИФМЕТИЧЕСКИЕ ОПЕРАТОРЫ
// ============================================================================
// `+`, `-`, `*`, `/`, `%`
// Унарный `-` — арифметическое отрицание (реализует трейт `Neg`).
// Унарный `!` — логическое/побитовое НЕ (реализует трейт `Not`).
//
// В debug-режиме переполнение целых вызывает панику; в release —
// «заворачивается». Для явного контроля есть `wrapping_*`,
// `checked_*`, `saturating_*`, `overflowing_*`.

fn arithmetic_demo() {
    let a = 17;
    let b = 5;

    println!("a = {a}, b = {b}");
    println!("a + b = {}", a + b);      // сложение
    println!("a - b = {}", a - b);      // вычитание
    println!("a * b = {}", a * b);      // умножение
    println!("a / b = {}", a / b);      // целочисленное деление (результат 3)
    println!("a % b = {}", a % b);      // остаток от деления (результат 2)

    // Унарный минус:
    let negative = -a;
    println!("-a = {negative}");

    // Унарный `!` для bool:
    let flag = true;
    println!("!flag = {}", !flag);      // false

    // Унарный `!` для целого — побитовое НЕ:
    let x: u8 = 0b1010_1010;
    println!("!x (для u8) = {:#010b}", !x);

    // Переполнение: используем checked_*, чтобы не было паники.
    let max = u8::MAX;
    println!("max + 1 (checked) = {:?}", max.checked_add(1)); // None

    // Вещественная арифметика:
    let f1 = 7.5_f64;
    let f2 = 2.0_f64;
    println!("f1 / f2 = {}", f1 / f2);
}

// ============================================================================
// 2. ОПЕРАТОРЫ СРАВНЕНИЯ
// ============================================================================
// `==`, `!=`, `<`, `<=`, `>`, `>=`
// Для встроенных типов и типов, реализующих `PartialEq`/`PartialOrd`.
// Возвращают `bool`.
//
// ВАЖНО: операторы `<`, `<=`, `>`, `>=` для `f32`/`f64` возвращают `false`,
// если один из операндов — `NaN`. Для полного порядка используйте
// `partial_cmp` и обрабатывайте `None`.

fn comparison_demo() {
    let x = 10;
    let y = 20;

    println!("x == y: {}", x == y);    // false
    println!("x != y: {}", x != y);    // true
    println!("x <  y: {}", x < y);     // true
    println!("x <= y: {}", x <= y);    // true
    println!("x >  y: {}", x > y);     // false
    println!("x >= y: {}", x >= y);    // false

    // Сравнение с NaN:
    let nan = f64::NAN;
    println!("nan == nan: {}", nan == nan); // false
    println!("nan <  1.0: {}", nan < 1.0); // false
    println!("nan.partial_cmp(&1.0) = {:?}", nan.partial_cmp(&1.0)); // None
}

// ============================================================================
// 3. ЛОГИЧЕСКИЕ ОПЕРАТОРЫ (КОРОТКОЕ ЗАМЫКАНИЕ)
// ============================================================================
// `&&` — логическое И с коротким замыканием.
// `||` — логическое ИЛИ с коротким замыканием.
// `!`  — логическое НЕ.
//
// «Короткое замыкание» означает, что правый операнд не вычисляется,
// если результат уже известен по левому.

fn bool_value() -> bool {
    println!("  -> bool_value() вызвана");
    true
}

fn logical_demo() {
    let t = true;
    let f = false;

    println!("t && f = {}", t && f);
    println!("t || f = {}", t || f);
    println!("!t     = {}", !t);

    // Демонстрация короткого замыкания:
    println!("false && bool_value():");
    let _ = false && bool_value(); // bool_value() НЕ вызовется
    println!("true || bool_value():");
    let _ = true || bool_value();  // bool_value() НЕ вызовется

    // Сравните:
    println!("true && bool_value():");
    let _ = true && bool_value();  // bool_value() вызовется
}

// ============================================================================
// 4. ПОБИТОВЫЕ ОПЕРАТОРЫ
// ============================================================================
// `&`  — побитовое И
// `|`  — побитовое ИЛИ
// `^`  — побитовое исключающее ИЛИ
// `!`  — побитовое НЕ
// `<<` — сдвиг влево
// `>>` — сдвиг вправо (для знаковых — арифметический, сохраняет знак)

fn bitwise_demo() {
    let a: u8 = 0b1100_1010; // 202
    let b: u8 = 0b1010_1100; // 172

    println!("a        = {a:#010b}");
    println!("b        = {b:#010b}");
    println!("a & b    = {:#010b}", a & b);   // 0b1000_1000
    println!("a | b    = {:#010b}", a | b);   // 0b1110_1110
    println!("a ^ b    = {:#010b}", a ^ b);   // 0b0110_0110
    println!("!a       = {:#010b}", !a);      // 0b0011_0101
    println!("a << 1   = {:#010b}", a << 1);  // 0b1001_0100
    println!("a >> 2   = {:#010b}", a >> 2);  // 0b0011_0010

    // Для знаковых сдвиг вправо сохраняет знак (арифметический сдвиг):
    let s: i8 = -8; // 0b1111_1000
    println!("s >> 1 = {} (арифметический сдвиг)", s >> 1); // -4
}

// ============================================================================
// 5. ПРИСВАИВАНИЕ И СОСТАВНЫЕ ПРИСВАИВАНИЯ
// ============================================================================
// `=` — простое присваивание.
// `+=`, `-=`, `*=`, `/=`, `%=`, `&=`, `|=`, `^=`, `<<=`, `>>=` — составные.
// Составное присваивание `x op= y` эквивалентно `x = x op y`
// (с точки зрения результата), но левый операнд вычисляется один раз.

fn assignment_demo() {
    let mut n = 10;

    n += 5;  // n = 15
    println!("после n += 5:  n = {n}");

    n -= 3;  // n = 12
    println!("после n -= 3:  n = {n}");

    n *= 2;  // n = 24
    println!("после n *= 2:  n = {n}");

    n /= 4;  // n = 6
    println!("после n /= 4:  n = {n}");

    n %= 4;  // n = 2
    println!("после n %= 4:  n = {n}");

    n <<= 3; // n = 16
    println!("после n <<= 3: n = {n}");

    n >>= 2; // n = 4
    println!("после n >>= 2: n = {n}");

    n |= 0b1000; // n = 12
    println!("после n |= 0b1000: n = {n}");

    n &= 0b1010; // n = 8
    println!("после n &= 0b1010: n = {n}");

    n ^= 0b1111; // n = 7
    println!("после n ^= 0b1111: n = {n}");
}

// ============================================================================
// 6. ДОСТУП К ПОЛЯМ, ВЫЗОВ МЕТОДА, ИНДЕКСАЦИЯ, ВЫЗОВ ФУНКЦИИ
// ============================================================================
// `.`  — доступ к полю, вызов метода, доступ к кортежному индексу.
// `[]` — индексация массива/среза/Vec и т.п.
// `()` — вызов функции/замыкания, группировка.

/// Структура для демонстрации доступа к полям и методам.
#[derive(Debug)]
struct Rectangle {
    width: f64,
    height: f64,
}

impl Rectangle {
    /// Метод экземпляра: доступ через `r.area()`.
    fn area(&self) -> f64 {
        self.width * self.height
    }

    /// Ассоциированная функция (без `self`): доступ через `Rectangle::new(...)`.
    fn new(width: f64, height: f64) -> Self {
        Self { width, height }
    }
}

fn access_demo() {
    let r = Rectangle::new(3.0, 4.0);

    // Доступ к полю через `.`:
    println!("r.width  = {}", r.width);
    println!("r.height = {}", r.height);

    // Вызов метода через `.`:
    println!("r.area() = {}", r.area());

    // Доступ к элементу кортежа через `.0`, `.1`:
    let t = (10, "hello", 3.14);
    println!("t.0 = {}, t.1 = {}, t.2 = {}", t.0, t.1, t.2);

    // Индексация массива/среза/Vec:
    let arr = [10, 20, 30, 40];
    println!("arr[0] = {}, arr[2] = {}", arr[0], arr[2]);

    let v = vec![1, 2, 3];
    println!("v[1] = {}", v[1]);

    // Вызов функции:
    let sum = arithmetic_sum(1, 2, 3);
    println!("arithmetic_sum(1, 2, 3) = {sum}");

    // Вызов замыкания (замыкание тоже вызывается через `()`):
    let double = |x: i32| x * 2;
    println!("double(21) = {}", double(21));

    // Группировка скобками для изменения порядка вычислений:
    let a = 2 + 3 * 4;      // 14
    let b = (2 + 3) * 4;    // 20
    println!("2 + 3 * 4 = {a}, (2 + 3) * 4 = {b}");
}

fn arithmetic_sum(a: i32, b: i32, c: i32) -> i32 {
    a + b + c
}

// ============================================================================
// 7. ПРИВЕДЕНИЕ ТИПОВ (`as`)
// ============================================================================
// `expr as Type` — явное приведение. Работает для числовых типов,
// указателей, `bool` -> целое и т.д. Может усекать значение.
//
// `as` — **не** перегрузочный оператор; это встроенная операция языка.

fn cast_demo() {
    let i: i32 = 42;

    // Целое -> вещественное:
    let f = i as f64;
    println!("42i32 as f64 = {f}");

    // Вещественное -> целое (дробная часть отбрасывается):
    let pi = 3.99_f64;
    let truncated = pi as i32;
    println!("3.99f64 as i32 = {truncated}"); // 3

    // Усечение: 300 не влезает в u8 (максимум 255) — получаем 300 % 256 = 44.
    let large = 300_i32;
    let wrapped = large as u8;
    println!("300i32 as u8 = {wrapped}");

    // bool -> целое:
    let t = true as u8;   // 1
    let f = false as u8;  // 0
    println!("true as u8 = {t}, false as u8 = {f}");

    // Символ -> целое (Unicode scalar value):
    let ch = 'A' as u32;
    println!("'A' as u32 = {ch}"); // 65
}

// ============================================================================
// 8. ОПЕРАТОР ПРОБРОСА ОШИБКИ (`?`)
// ============================================================================
// `expr?` — если `expr` возвращает `Err(e)`, немедленно вернуть `Err(e)`
// из текущей функции; если `Ok(v)` — «развернуть» в `v`.
// Работает в функциях, возвращающих `Result<T, E>` или `Option<T>`.
//
// Это синтаксический сахар над `match`, который делает код лаконичнее.

fn parse_number(s: &str) -> Result<i32, std::num::ParseIntError> {
    // Без `?` пришлось бы писать match. С `?` — одна строка.
    let n: i32 = s.parse()?;
    Ok(n * 2)
}

fn error_propagation_demo() {
    println!("parse_number(\"21\") = {:?}", parse_number("21"));   // Ok(42)
    println!("parse_number(\"abc\") = {:?}", parse_number("abc")); // Err(...)

    // `?` также работает с `Option`:
    fn first_char_upper(s: &str) -> Option<char> {
        let c = s.chars().next()?; // если строка пустая — вернётся None
        Some(c.to_ascii_uppercase())
    }

    println!("first_char_upper(\"hello\") = {:?}", first_char_upper("hello"));
    println!("first_char_upper(\"\") = {:?}", first_char_upper(""));
}

// ============================================================================
// 9. ДИАПАЗОНЫ (`..`, `..=`)
// ============================================================================
// `a..b`  — правый исключающий диапазон: `a <= x < b`.
// `a..=b` — правый включающий диапазон: `a <= x <= b`.
// `..b`, `a..`, `..` — открытые диапазоны (используются в срезах, match и т.д.).

fn range_demo() {
    // Диапазон как значение:
    let exclusive: std::ops::Range<i32> = 1..5;
    let inclusive: std::ops::RangeInclusive<i32> = 1..=5;

    println!("1..5  = {exclusive:?}");  // 1,2,3,4
    println!("1..=5 = {inclusive:?}");  // 1,2,3,4,5

    // Итерация по диапазону:
    let mut sum = 0;
    for i in 1..=5 {
        sum += i;
    }
    println!("сумма 1..=5 = {sum}"); // 15

    // Срезы с диапазонами:
    let arr = [10, 20, 30, 40, 50];
    println!("arr[1..4]  = {:?}", &arr[1..4]);  // [20, 30, 40]
    println!("arr[1..=3] = {:?}", &arr[1..=3]); // [20, 30, 40]

    // Открытые диапазоны в срезах:
    println!("arr[..2]  = {:?}", &arr[..2]);  // [10, 20]
    println!("arr[3..]  = {:?}", &arr[3..]);  // [40, 50]
    println!("arr[..]   = {:?}", &arr[..]);   // весь массив

    // Диапазоны в `match`:
    let n = 7;
    let category = match n {
        0..=9   => "цифра",
        10..=99 => "двузначное",
        _       => "что-то ещё",
    };
    println!("n = {n}, категория: {category}");
}

// ============================================================================
// 10. СПЕЦИАЛЬНЫЕ СИМВОЛЫ И ПУНКТУАЦИЯ
// ============================================================================
// `::`  — разделитель путей (`std::io`, `Rectangle::new`).
// `:`   — указание типа (`let x: i32`), инициализация поля структуры,
//         метка цикла (`'outer: loop`).
// `;`   — терминатор операторов и элементов.
// `->`  — возвращаемый тип функции/замыкания.
// `=>`  — разделитель в `match`.
// `@`   — связывание в шаблоне.
// `_`   — wildcard-шаблон, выведенный тип, разделитель в литералах.
// `#`   — атрибуты (`#[derive(Debug)]`).
// `$`   — макросы (`$name:expr`).
// `,`   — разделитель аргументов, элементов, полей.

fn special_symbols_demo() {
    // `:` — указание типа и инициализация поля:
    let _x: i32 = 10;

    // `;` — терминатор оператора:
    let _y = 20;

    // `->` — возвращаемый тип (см. объявления функций в этом файле).

    // `=>` — ветвь match:
    let n = 1;
    match n {
        1 => println!("один"),
        _ => println!("другое"),
    }

    // `@` — связывание значения с переменной внутри шаблона:
    let value = 15;
    match value {
        n @ 10..=20 => println!("n = {n} попадает в 10..=20"),
        _ => println!("вне диапазона"),
    }

    // `_` — wildcard:
    let (first, _) = (1, 2);
    println!("first = {first}");

    // `_` в числовом литерале — разделитель разрядов:
    let million = 1_000_000;
    println!("million = {million}");

    // `::` — путь к ассоциированной функции:
    let r = Rectangle::new(1.0, 2.0);
    println!("Rectangle::new(1.0, 2.0) = {:?}", r);

    // `:` — метка цикла:
    'outer: loop {
        for i in 0..3 {
            if i == 1 {
                break 'outer; // выход из внешнего цикла по метке
            }
        }
    }
    println!("вышли из внешнего цикла по метке");
}

// ============================================================================
// 11. ПРИОРИТЕТ ОПЕРАТОРОВ
// ============================================================================
// Порядок вычислений в Rust похож на C-подобные языки.
// От самого сильного к самому слабому (упрощённо):
//
//   1. Пути, вызовы методов, доступ к полям     (левая ассоциативность)
//   2. Вызовы функций, индексация               (левая)
//   3. Унарные `- * ! & &mut`, `as`             (левая)
//   4. `* / %`                                  (левая)
//   5. `+ -`                                    (левая)
//   6. `<< >>`                                  (левая)
//   7. `&`                                      (левая)
//   8. `^`                                      (левая)
//   9. `|`                                      (левая)
//  10. `== != < <= > >=`                        (требуют скобок при смешивании)
//  11. `&&`                                     (левая)
//  12. `||`                                     (левая)
//  13. `.. ..=`                                 (требуют скобок)
//  14. `= += -= *= /= %= &= |= ^= <<= >>=`      (правая)
//  15. `return break` замыкания

fn precedence_demo() {
    // Умножение связывает сильнее сложения:
    let a = 2 + 3 * 4;        // 2 + 12 = 14
    println!("2 + 3 * 4 = {a}");

    // Скобки меняют порядок:
    let b = (2 + 3) * 4;      // 20
    println!("(2 + 3) * 4 = {b}");

    // Побитовые операторы слабее сравнений? Нет: сравнения слабее побитовых,
    // но в Rust смешивать `&` и `==` без скобок неудобно — компилятор
    // потребует скобок. Явно расставим:
    let x = 0b1010 & 0b0110; // 0b0010
    let y = (x == 0b0010);
    println!("(0b1010 & 0b0110) == 0b0010: {y}");

    // `&&` связывает сильнее `||`:
    let t = true || false && false; // true || (false && false) = true
    println!("true || false && false = {t}");

    // Оператор `as` связывает сильнее арифметики? Нет — `as` в Rust
    // имеет довольно высокий приоритет, но не выше вызовов методов.
    let n = 1 + 2 as i64 * 3; // 1 + ((2 as i64) * 3) = 7
    println!("1 + 2 as i64 * 3 = {n}");
}

// ============================================================================
// 12. ПЕРЕГРУЗКА ОПЕРАТОРОВ ЧЕРЕЗ ТРЕЙТЫ
// ============================================================================
// Большинство операторов — синтаксический сахар над методами трейтов
// из `std::ops`:
//   `a + b`  -> `a.add(b)`      (трейт `Add`)
//   `-a`     -> `a.neg()`       (трейт `Neg`)
//   `!a`     -> `a.not()`       (трейт `Not`)
//   `a == b` -> `a.eq(&b)`      (трейт `PartialEq`)
//   и т.д.
//
// Перегрузка допустима только для операторов, у которых есть
// соответствующий трейт. Например, `=` перегрузить нельзя.

/// Простой тип «комплексное число» для демонстрации перегрузки.
#[derive(Debug, Clone, Copy, PartialEq)]
struct Complex {
    re: f64,
    im: f64,
}

impl Complex {
    fn new(re: f64, im: f64) -> Self {
        Self { re, im }
    }
}

// Реализация `+` для `Complex + Complex`:
impl Add for Complex {
    type Output = Complex;

    fn add(self, rhs: Self) -> Self::Output {
        Complex::new(self.re + rhs.re, self.im + rhs.im)
    }
}

// Реализация унарного `-` для `Complex`:
impl Neg for Complex {
    type Output = Complex;

    fn neg(self) -> Self::Output {
        Complex::new(-self.re, -self.im)
    }
}

// Реализация `!` для `Complex` — «сопряжение» (не совсем логическое НЕ,
// но демонстрирует перегрузку `Not`).
impl Not for Complex {
    type Output = Complex;

    fn not(self) -> Self::Output {
        Complex::new(self.re, -self.im)
    }
}

// Реализация `Display` — не оператор, но полезно для печати:
impl fmt::Display for Complex {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.im >= 0.0 {
            write!(f, "{:.1} + {:.1}i", self.re, self.im)
        } else {
            write!(f, "{:.1} - {:.1}i", self.re, -self.im)
        }
    }
}

fn operator_overloading_demo() {
    let a = Complex::new(1.0, 2.0);
    let b = Complex::new(3.0, -1.0);

    println!("a = {a}");
    println!("b = {b}");

    // `+` работает благодаря `impl Add for Complex`:
    let sum = a + b;
    println!("a + b = {sum}");

    // Унарный `-` благодаря `impl Neg`:
    let neg = -a;
    println!("-a = {neg}");

    // `!` благодаря `impl Not`:
    let conjugate = !a;
    println!("!a = {conjugate}");

    // `==` и `!=` благодаря `#[derive(PartialEq)]`:
    let c = Complex::new(1.0, 2.0);
    println!("a == c: {}", a == c); // true
    println!("a != b: {}", a != b); // true
}

